"""
The SPICE netlist emitter: ¢ DAG → SPICE netlist.

Bridges from the Python ¢ representation to a runnable hardware description
that a SPICE simulator (ngspice, LTspice) can consume.

Currently supports emitting netlists for:
  - op-amp + multiplier sqrt extractor (¢_sqrt via ¢_eq)
  - delta-sigma modulator (¢_accum + ¢_wrap + ¢_eq)
  - RC integrator (¢_accum via capacitor)
  - KCL summer (¢_sum)

Each netlist is a complete, self-contained .cir file.
"""
from __future__ import annotations
from typing import Optional
from .grammar import CGraph


def generate_spice_netlist(impl_name: str = "opamp_sqrt", **params) -> str:
    """Generate a SPICE netlist for a named ∆ implementation."""
    if impl_name == "opamp_sqrt":
        return _netlist_opamp_sqrt(params.get("v_in", 5.0))
    elif impl_name == "multiplier":
        return _netlist_multiplier(params.get("v_in1", 1000.0), params.get("v_in2", 0.005))
    elif impl_name == "divider":
        return _netlist_divider(params.get("v_num", 5.0), params.get("v_den", 2.0))
    elif impl_name == "diode_exp":
        return _netlist_diode_exp(params.get("v_in", 0.7))
    elif impl_name == "log_amp":
        return _netlist_log_amp(params.get("i_in", 1e-3))
    elif impl_name == "clipper":
        return _netlist_clipper(params.get("v_in", 5.0), params.get("v_clip", 3.0))
    elif impl_name == "delta_sigma":
        return _netlist_delta_sigma(params.get("input_value", 0.7), params.get("n_samples", 1000))
    elif impl_name == "rc_integrator":
        return _netlist_rc_integrator(params.get("v_in", 1.0), params.get("r", 1000), params.get("c", 1e-6))
    elif impl_name == "kcl_summer":
        return _netlist_kcl_summer(params.get("inputs", [3.0, 5.0, -2.0]))
    else:
        raise ValueError(f"unknown implementation: {impl_name}")


def _netlist_opamp_sqrt(v_in: float) -> str:
    return f"""* ============================================================
* Op-amp + analog multiplier square root extractor
* Generated by the cent compiler
*
* £:  V_out = sqrt(V_in)
* ¢:  scale(V_in, 1) -> div(_, 1) -> sqrt(_) -> V_out
*     (degenerates to: V_out^2 = V_in, solved by feedback)
* ∆:  op-amp (U1) + analog multiplier (U2) in feedback loop
*
* Equilibrium: V_out^2 / 10 = V_in  ->  V_out = sqrt(10 * V_in)
* With V_in = {v_in}V: V_out = sqrt({10*v_in}) = {(10*v_in)**0.5:.6f}V
* ============================================================

VIN 1 0 DC {v_in}
EOUT 3 0 1 2 1e6
EMULT 4 0 VALUE = {{ V(3) * V(3) / 10.0 }}
R1 4 2 1k
Rg 2 0 1meg
.OP
.PRINT DC V(3)
.END
"""


def _netlist_multiplier(v_in1: float, v_in2: float) -> str:
    """AD633 analog multiplier with real scale factor (/10, no cancelling gain stage).

    The AD633's output IS V(1)*V(2)/10 — that's the real component behavior.
    We do NOT add a *10 gain stage to cancel it. The test must compare
    V(3) to P*A/10, acknowledging the component's real scale factor.

    Physical error sources (documented, not simulated here):
    - Nonlinearity: ±0.5% typical (AD633JN datasheet)
    - Bandwidth: 1 MHz
    - Offset voltage: ±50 mV
    """
    return f"""* ============================================================
* AD633 Analog Multiplier (real component, no cancelling gain)
* Generated by the cent compiler
*
* £:  F = P × A  (force = pressure × area)
* ¢:  mult(P, A) → F
* ∆:  AD633 analog multiplier
*
* IMPORTANT: The AD633 output is V(3) = V(1)*V(2)/10, NOT V(1)*V(2).
* The /10 is the REAL AD633 scale factor (datasheet, not a bug).
* We do NOT add a *10 gain stage — that would be tautological.
* The test compares V(3) to expected = P*A/10.
*
* Physical error sources (per AD633JN datasheet):
*   Nonlinearity: ±0.5% typical
*   Bandwidth: 1 MHz
*   Offset: ±50 mV
* ============================================================

VIN1 1 0 DC {v_in1}
VIN2 2 0 DC {v_in2}

* AD633 subcircuit (simplified model with documented specs)
XU1 1 2 3 AD633
RLOAD 3 0 10k

.SUBCKT AD633 X Y Z
* V(Z) = V(X) * V(Y) / 10  (AD633 transfer function, datasheet pg 3)
* Nonlinearity not modeled in .OP (nominal value only)
EMULT Z 0 VALUE = {{ V(X) * V(Y) / 10.0 }}
.ENDS

* Analysis: DC operating point
.OP
.PRINT DC V(3)

* Sweep 3 input pairs (run separately or use .STEP):
* Pair 1: P=1000, A=0.005 → expected V(3) = 0.500
* Pair 2: P=500,  A=0.01  → expected V(3) = 0.500
* Pair 3: P=2000, A=0.002 → expected V(3) = 0.400

* Measure equilibrium error
.MEASURE DC vout PARAM='V(3)'
.MEASURE DC expected PARAM='{v_in1} * {v_in2} / 10.0'
.MEASURE DC error_pct PARAM='abs(V(3) - {v_in1} * {v_in2} / 10.0) / ({v_in1} * {v_in2} / 10.0) * 100'

* Behavioral model note: This .cir uses a behavioral EMULT source for
* mathematical verification. Physical validation (with nonlinearity,
* parasitics, temperature drift) requires ngspice/LTspice with the
* full AD633 macro-model from Analog Devices.

.END
"""


def _netlist_divider(v_num: float, v_den: float) -> str:
    return f"""* Analog divider: V_out = V_num / V_den
* ¢: div(V_num, V_den) → V_out
* Uses op-amp + multiplier in feedback: V_out = 10 * V_num / V_den
VNUM 1 0 DC {v_num}
VDEN 2 0 DC {v_den}
EOUT 3 0 1 4 1e6
EMULT 4 0 VALUE = {{ V(3) * V(2) / 10.0 }}
R1 4 0 1k
.OP
.PRINT DC V(3)
.END
"""


def _netlist_diode_exp(v_in: float) -> str:
    return f"""* Diode exponential: I = Is * exp(V / Vt)
* ¢: exp(V) → I
* Vt = 25.85mV at 300K, Is = 1e-12 A
VIN 1 0 DC {v_in}
D1 1 0 DIODE_EXP
.MODEL DIODE_EXP D(IS=1e-12 N=1)
.OP
.PRINT DC I(D1)
.END
"""


def _netlist_log_amp(i_in: float) -> str:
    return f"""* Log amplifier: V = Vt * ln(I / Is)
* ¢: log(I) → V
* Uses diode in op-amp feedback: V_out = -Vt * ln(I_in / Is)
IIN 1 0 DC {i_in}
XU1 0 2 3 OPAMP_IDEAL
D1 3 2 DIODE_LOG
.MODEL DIODE_LOG D(IS=1e-12 N=1)
R1 1 2 1k
.SUBCKT OPAMP_IDEAL NI INV OUT
EOUT OUT 0 NI INV 1e6
.ENDS
.OP
.PRINT DC V(3)
.END
"""


def _netlist_clipper(v_in: float, v_clip: float) -> str:
    return f"""* Op-amp clipper: V_out = tanh(V_in) (approximated by zener clipping)
* ¢: sat(V_in) → V_out
* Zener diodes clip at ±{v_clip}V
VIN 1 0 DC {v_in}
R1 1 2 1k
D1 2 0 ZENER_POS
D2 0 2 ZENER_NEG
.MODEL ZENER_POS D(BV={v_clip} IBV=1e-3)
.MODEL ZENER_NEG D(BV={v_clip} IBV=1e-3)
.OP
.PRINT DC V(2)
.END
"""


def _netlist_delta_sigma(input_value: float, n_samples: int) -> str:
    return f"""* ============================================================
* Delta-Sigma modulator (first-order)
* Generated by the cent compiler
*
* £:  Q(t) = ∫I(t)dt  (temporal integration)
* ¢:  accum(I) -> wrap(quantizer) -> eq(feedback)
* ∆:  delta-sigma modulator (digital, temporal carrier)
*
* Input: I = {input_value} (constant)
* Samples: {n_samples}
* Expected: running_sum(bitstream) -> {input_value * n_samples}
* ============================================================

* This is a behavioral model — real delta-sigma requires
* a mixed-signal simulator (e.g., Verilog-AMS).
* The Python simulation in simulator.py provides the
* bitstream-level verification.

VIN 1 0 DC {input_value}
* Integrator (op-amp + capacitor)
EINT 2 0 VALUE = {{ 0 }} ; behavioral integrator
* Quantizer (comparator)
EQUANT 3 0 VALUE = {{ IF(V(2)>0, 1, -1) }}
* Feedback
RFB 3 2 1k
CINT 2 0 1u
.OP
.PRINT DC V(3)
.END
"""


def _netlist_rc_integrator(v_in: float, r: float, c: float) -> str:
    return f"""* ============================================================
* RC integrator (capacitor-based temporal integration)
* Generated by the cent compiler
*
* £:  V_out(t) = (1/RC) · ∫V_in(t)dt
* ¢:  accum(V_in) -> scale(1/RC) -> V_out
* ∆:  resistor + capacitor (electrical, temporal carrier)
* ============================================================

VIN 1 0 DC {v_in}
R1 1 2 {r}
C1 2 0 {c}
.IC V(2) = 0
.TRAN 1u 1m
.PRINT TRAN V(2)
.END
"""


def _netlist_kcl_summer(inputs: list) -> str:
    lines = ["* ============================================================",
             "* KCL node summer",
             "* Generated by the cent compiler",
             "*",
             "* £:  I_total = I1 + I2 + I3",
             "* ¢:  sum(I1, I2) -> sum(_, I3) -> I_total",
             "* ∆:  KCL node (electrical, temporal carrier)",
             "* ============================================================", ""]
    for i, val in enumerate(inputs):
        lines.append(f"I{i+1} 0 1 DC {val}")
    lines.append("")
    lines.append(".OP")
    lines.append(".PRINT DC I(I1) I(I2) I(I3)")
    lines.append(".END")
    return "\n".join(lines) + "\n"


def emit_for_cent_dag(dag: CGraph, target_name: str = "opamp_sqrt") -> str:
    """Pick the right netlist based on the ¢ DAG's structure."""
    ops = [op.op for op in dag.ops]
    if "sqrt" in ops:
        return generate_spice_netlist("opamp_sqrt")
    elif "accum" in ops and "wrap" in ops:
        return generate_spice_netlist("delta_sigma")
    elif "accum" in ops:
        return generate_spice_netlist("rc_integrator")
    elif "sum" in ops:
        return generate_spice_netlist("kcl_summer")
    else:
        return f"* No SPICE template for ¢ ops: {ops}\n"


def write_spice_netlist(impl_name: str = "opamp_sqrt", filepath: str = None, **params) -> str:
    """Generate a SPICE netlist AND write it to disk as a .cir file."""
    netlist = generate_spice_netlist(impl_name, **params)
    if filepath is None:
        filenames = {
            "opamp_sqrt": "sqrt_extractor.cir",
            "multiplier": "multiplier.cir",
            "divider": "divider.cir",
            "diode_exp": "diode_exp.cir",
            "log_amp": "log_amp.cir",
            "clipper": "clipper.cir",
            "delta_sigma": "delta_sigma_modulator.cir",
            "rc_integrator": "rc_integrator.cir",
            "kcl_summer": "kcl_summer.cir",
        }
        filepath = filenames.get(impl_name, f"{impl_name}.cir")
    with open(filepath, "w") as f:
        f.write(netlist)
    return filepath
