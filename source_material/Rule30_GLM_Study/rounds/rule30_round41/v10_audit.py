#!/usr/bin/env python3
"""Round 41 — audit of `hypothesis_engine_v10.py` (the self-dialogue script).

Static checks only (the script is not executed):
  1. can it run here?  its imports and the stage methods it calls;
  2. are its utterances generated?  every string passed to `speak(...)` is collected; the fixed
     text (outside `{...}` placeholders) is what the engine would say regardless of its data;
  3. are the numbers in that fixed text grounded?  the Round 41 guard checks them against the
     ledger facts in knowledge.json (nothing is computed by fixed text, so only the ledger counts);
  4. are its mathematical claims right?  the fixed sentences that state an implication are matched
     to the checked edges in knowledge.json.

Run: python3 v10_audit.py [path/to/hypothesis_engine_v10.py]   → writes v10_audit.md
"""

from __future__ import annotations

import ast
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from glm_dialogue import Guard, Knowledge, numbers_in  # noqa: E402

SRC = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE.parent / "hypothesis_engine_v10.py"

# fixed sentences that state a mathematical implication → (edge premise tag, what v10 says)
CLAIMS = [
    ("cannot be generated by any finite automaton", "rule30.centre_aperiodic",
     "aperiodic ⟹ no finite automaton generates the column"),
    ("This IMPLIES the centre column is aperiodic", "rule30.transient_at_read",
     "transient longer than D ⟹ centre column aperiodic"),
    ("infinitely many period-doubling events", "law:lp:white(D-1) ∧ odd(D-2)",
     "periods unbounded ⟹ infinitely many odd-parity white diagonals"),
]


def speak_strings(tree):
    out = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Call) and getattr(node.func, "attr", None) == "speak":
            for arg in node.args[:1]:
                out.append((node.lineno, fixed_text(arg)))
    return out


def fixed_text(node) -> str:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    if isinstance(node, ast.JoinedStr):
        return "".join(v.value if isinstance(v, ast.Constant) else "{…}" for v in node.values)
    if isinstance(node, ast.BinOp):
        return fixed_text(node.left) + fixed_text(node.right)
    return "{…}"


def main():
    src = SRC.read_text()
    tree = ast.parse(src)
    know = Knowledge.load(HERE / "knowledge.json")
    guard = Guard(know.numbers())
    lines = ["# Audit of `hypothesis_engine_v10.py` (generated by `v10_audit.py`)", ""]

    # 1. runnable?
    imports = [(n.module, [a.name for a in n.names]) for n in ast.walk(tree)
               if isinstance(n, ast.ImportFrom) and n.module and "hypothesis" in n.module]
    lines += ["## 1. Can it run in this project?", ""]
    for mod, names in imports:
        found = sorted(str(p.relative_to(HERE.parent)) for p in HERE.parent.rglob(f"{mod}.py")
                       if "glm_repo" not in str(p))
        lines.append(f"* `from {mod} import {', '.join(names)}` → "
                     + (f"found at {', '.join('`' + f + '`' for f in found)}" if found
                        else "**not found anywhere in the project**"))
    calls = sorted({n.func.attr for n in ast.walk(tree) if isinstance(n, ast.Call)
                    and isinstance(n.func, ast.Attribute) and isinstance(n.func.value, ast.Name)
                    and n.func.value.id == "self" and n.func.attr.startswith("run_")})
    eng = HERE.parent / "rule30_round38" / "hypothesis_engine.py"
    have = set()
    if eng.exists():
        have = {n.name for n in ast.walk(ast.parse(eng.read_text()))
                if isinstance(n, ast.FunctionDef)}
    lines.append(f"* stage methods called on `self`: "
                 + ", ".join(f"`{c}`" + ("" if c in have else " (missing from the Round 38 "
                                                              "engine)") for c in calls))
    lines.append("")

    # 2./3. fixed text and its numbers
    strings = speak_strings(tree)
    lines += ["## 2. Utterances: fixed text vs. data", "",
              f"`speak(...)` is called at {len(strings)} places. The fixed text below is what the "
              f"engine says whatever its data are; `{{…}}` marks the parts filled in from data.",
              "", "| line | fixed text | numbers not in the ledger |", "|---|---|---|"]
    n_fixed = n_bad = 0
    for ln, txt in strings:
        plain = txt.replace("{…}", "")
        if len(plain.strip()) > 60:
            n_fixed += 1
        bad = guard.ungrounded(txt)
        n_bad += bool(bad)
        if bad or len(plain.strip()) > 60:
            short = txt if len(txt) < 230 else txt[:227] + "…"
            lines.append(f"| {ln} | {short.replace('|', '/')} | {bad if bad else ''} |")
    lines += ["", f"{n_fixed} utterances are mostly fixed text; {n_bad} contain numbers that "
                  f"appear nowhere in the ledger.", ""]

    # 4. implication claims
    lines += ["## 3. Mathematical claims in the fixed text", "",
              "| v10 sentence | claim | verdict | backing |", "|---|---|---|---|"]
    for needle, tag, claim in CLAIMS:
        hit = any(needle in t for _, t in strings)
        edges = know.about({tag})
        verdicts = "; ".join(f"{e.verdict}: {e.conclusion}" for e in edges) or "—"
        backing = "; ".join(e.backing for e in edges) or "—"
        lines.append(f"| {'present' if hit else 'absent'}: “{needle}” | {claim} | {verdicts} | "
                     f"{backing} |")
    out = HERE / "v10_audit.md"
    out.write_text("\n".join(lines) + "\n")
    print(out.read_text())


if __name__ == "__main__":
    main()
