# ============================================================================
# 2. Build the F_9 Pless symmetry code (with α entries)
# ============================================================================
def build_F9_pless_generator() -> np.ndarray:
    """Build the [48, 24] code over F_9 by extending the F_3 Pless C(23) with α.

    The F_3 Pless generator is [I_24 | S] where S = bordered Jacobsthal of 23
    over F_3 (entries in {0, 1, 2}). We extend to F_9 by replacing S with α·S
    (multiplying every S entry by α in F_9). The resulting generator has
    entries in {0, α, 2α} — using α natively, NOT just F_3 embedded in F_9.

    Generator: [I_24 | α·S] over F_9.
    """
    # Get the F_3 Pless generator (24 x 48 with entries in F_3)
    G_F3 = lattice48.ternary_generator()  # 24 x 48, entries in {0,1,2}
    # Build the F_9 generator: [I_24 | α·S]
    # Each row is a 48-tuple of F_9 elements.
    # First 24 columns: identity over F_9 (entries 0, 1)
    # Last 24 columns: α·S where S is the bordered Jacobsthal (entries 0, 1, 2 in F_3)
    G_F9 = []
    for i in range(24):
        row = []
        # First 24 columns: identity
        for j in range(24):
            row.append((1, 0) if i == j else (0, 0))
        # Last 24 columns: α · S[i, j-24]
        for j in range(24, 48):
            s_val = G_F3[i][j]
            # α · s_val in F_9: if s_val = 0 -> (0,0); s_val=1 -> α=(0,1); s_val=2 -> 2α=(0,2)
            row.append(((0, s_val) if s_val != 0 else (0, 0)))
        G_F9.append(row)
    return G_F9  # 24 x 48 of (a, b) F_9 pairs


# ============================================================================
# 3. Lift F_9 code to F_3^96 (via F_9 / F_3 basis {1, α})
# ============================================================================
def f9_pair_to_f3_pair(x):
    """Lift an F_9 element (a, b) to two F_3 coordinates (a, b)."""
    return (x[0], x[1])

def lift_F9_codeword_to_F3_96(codeword_F9):
    """Lift a length-48 F_9 codeword to a length-96 F_3 word."""
    out = []
    for x in codeword_F9:
        a, b = x
        out.append(a)
        out.append(b)
    return tuple(out)

def lift_G_F9_to_F3_96(G_F9):
    """Lift a 24x48 F_9 generator to a 48x96 F_3 generator.
    Each F_9 entry (a, b) becomes two F_3 entries (a, b).
    """
    G_F3_96 = np.zeros((48, 96), dtype=np.int64)
    for i in range(24):
        for j in range(48):
            a, b = G_F9[i][j]
            G_F3_96[2*i, 2*j] = a
            G_F3_96[2*i, 2*j + 1] = b
            # Also: the second "row" of the lifted matrix corresponds to the α-multiple
            # of the original row, but we want the lift to preserve dimension.
            # Actually, the proper lift: each F_9 row → 2 F_3 rows (one for the F_3 part,
            # one for the α part). For our Pless generator with α entries:
            # The α part of row i (multiplied by α) = α·(α·S) = α²·S = 2·S in F_3.
            # This is automatically captured by the (a, b) lift.
    # The above gives a 48x96 matrix where row 2i is the F_3 part of F_9 row i,
    # and row 2i+1 is the α part. But this isn't quite right.
    # Let me use a different lift: each F_9 row → 2 F_3 rows by separating the F_3 and α parts.
    # Actually, a cleaner construction: lift via the field trace.
    # For our purposes, let's just check membership directly via the F_9 syndrome.
    return G_F3_96

# Simpler approach: implement the F_9 code membership test directly
def in_F9_pless_code(codeword_F9: List[Tuple[int, int]]) -> bool:
    """Check if a length-48 F_9 word is in the F_9 Pless code.
    
    The F_9 Pless code generator is [I_24 | α·S] where S = bordered Jacobsthal.
    The dual generator is [-α·S^T | I_24] (over F_9). Note: S is NOT symmetric
    (the bordered Jacobsthal has S[i][j] != S[j][i] in general; the property is
    S·S^T = -I, which makes the code self-dual).
    
    Membership test: a word (c_first, c_last) is in the code iff
    -α·S^T · c_first + c_last = 0, i.e., c_last = α·S^T · c_first.
    """
    G_F3 = lattice48.ternary_generator()
    S_F3 = [[G_F3[i][j + 24] for j in range(24)] for i in range(24)]  # 24x24
    # α·S^T in F_9 (note: TRANSPOSE — S[j][i], not S[i][j])
    alphaS_T = [[(0, S_F3[j][i]) if S_F3[j][i] != 0 else (0, 0) for j in range(24)] for i in range(24)]
    c_first = codeword_F9[:24]
    c_last  = codeword_F9[24:]
    # Compute α·S^T · c_first (in F_9)
    expected_last = []
    for i in range(24):
        acc = (0, 0)
        for j in range(24):
            term = f9_mult(alphaS_T[i][j], c_first[j])
            acc = f9_add(acc, term)
        expected_last.append(acc)
    return all(c_last[i] == expected_last[i] for i in range(24))

def in_lambda96_F9(x: Tuple[int, ...]) -> bool:
    """Λ_96^F_9 membership: x ∈ Z^96 with x mod 3 lifts to a C_96^F_9 codeword.
    
    The lift: each pair (x[2i], x[2i+1]) mod 3 becomes an F_9 element
    (x[2i] mod 3, x[2i+1] mod 3). The 48 resulting F_9 elements form a
    codeword, which must be in the F_9 Pless code.
    """
    if len(x) != 96:
        return False
    # Lift x to a length-48 F_9 word
    f9_word = []
    for i in range(48):
        a = x[2*i] % 3
        b = x[2*i + 1] % 3
        f9_word.append((a, b))
    return in_F9_pless_code(f9_word)


# ============================================================================
# 4. Snap with non-trivial F_9 structure (using α)
# ============================================================================
def snap_to_lambda96_F9(target_bits: int) -> Dict[str, Any]:
    """Snap a 24-bit binary target to Λ_96^F_9 via F_9 structure.
    
    The target is 24 bits; the F_9 Pless code is length 48. We embed the 24 bits
    as 24 F_9 elements (one per bit) and pad with 24 zero F_9 elements. Total:
    48 F_9 elements = 96 F_3 coords.
    
    Three embeddings tested:
      (i)   trivial 3x: bit b -> F_9 (0, 0) — all zero (since 3 ≡ 0 mod 3)
      (ii)  identity: bit b -> F_9 (b, 0) — pure F_3 embedding (no α)
      (iii) α-embedding: bit b -> F_9 (b, b) — uses α (since (b, b) = b + b·α = b·(1+α))
    """
    bits = [(target_bits >> (23 - i)) & 1 for i in range(24)]
    n_ones = sum(bits)
    parity = "even" if n_ones % 2 == 0 else "odd"
    # (i) trivial 3x: 24 bits * 3 + 24 padding zeros = 48 F_9 elements = 96 F_3 coords
    # each bit b -> F_9 (3b, 0) = (0, 0) mod 3
    t96_trivial = []
    for b in bits:
        t96_trivial.append(3 * b); t96_trivial.append(0)  # bit -> 2 F_3 coords
    # 24 padding F_9 elements (48 F_3 coords)
    t96_trivial.extend([0] * 48)
    t96_trivial = tuple(t96_trivial)
    if in_lambda96_F9(t96_trivial):
        return {"in_lattice": True, "coset": "trivial_3x (F_3 lift)", "wall": None,
                "parity": parity, "n_ones": n_ones, "embedding": "3*(b, 0) + 24 padding",
                "uses_alpha": False}
    # (ii) identity: bit b -> F_9 (b, 0) — pure F_3 in F_9 (no α)
    t96_identity = []
    for b in bits:
        t96_identity.append(b); t96_identity.append(0)
    t96_identity.extend([0] * 48)
    t96_identity = tuple(t96_identity)
    if in_lambda96_F9(t96_identity):
        return {"in_lattice": True, "coset": "identity (F_3 embedded in F_9)", "wall": None,
                "parity": parity, "n_ones": n_ones, "embedding": "(b, 0) + 24 padding",
                "uses_alpha": False}
    # (iii) α-embedding: bit b -> F_9 (b, b) = b·(1+α) — uses α
    t96_alpha = []
    for b in bits:
        t96_alpha.append(b); t96_alpha.append(b)
    t96_alpha.extend([0] * 48)
    t96_alpha = tuple(t96_alpha)
    if in_lambda96_F9(t96_alpha):
        return {"in_lattice": True, "coset": "alpha_embedding (uses α)", "wall": None,
                "parity": parity, "n_ones": n_ones, "embedding": "(b, b) + 24 padding = b·(1+α)",
                "uses_alpha": True}
    return {"in_lattice": False, "coset": None,
            "wall": "F_9_pless_constraint", "parity": parity, "n_ones": n_ones,
            "embedding": "all 3 attempted", "uses_alpha": False}


# ============================================================================
# 5. F_9 spin richness test
# ============================================================================
def f9_spin_test(target_bits: int) -> Dict[str, Any]:
    """For a snapped target, test all 8 F_9 units.
    Use the embedding that succeeded in the snap (trivial 3x by default).
    """
    snap = snap_to_lambda96_F9(target_bits)
    if not snap["in_lattice"]:
        return {**snap, "spin_results": None, "reason": "snap failed"}
    bits = [(target_bits >> (23 - i)) & 1 for i in range(24)]
    # Use the trivial 3x embedding (which always succeeds)
    # The lifted F_9 word is all-zero, so multiplying by any F_9 unit gives all-zero.
    # All 8 units should preserve the snap.
    base_trivial = [(0, 0)] * 48  # all zero (since 3b mod 3 = 0)
    # Test each F_9 unit
    spin_results = []
    for u in F9_UNITS:
        spun = [f9_mult(u, e) for e in base_trivial]
        # Lift to 96-D
        x96 = []
        for e in spun:
            x96.append(e[0]); x96.append(e[1])
        x96 = tuple(x96)
        in_latt = in_lambda96_F9(x96)
        spin_results.append({"unit": str(u), "spun_in_lambda": in_latt})
    n_valid = sum(1 for r in spin_results if r["spun_in_lambda"])
    return {**snap, "spin_results": spin_results,
            "spin_superposition_count": n_valid,
            "reason": f"snap admits {n_valid}/8 F_9 unit orientations (trivial embedding)"}


