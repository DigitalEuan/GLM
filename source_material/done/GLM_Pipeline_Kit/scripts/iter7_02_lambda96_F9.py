# 1. F_9 arithmetic
# ============================================================================
# F_9 = F_3[α] / (α² + 1), so α² = -1 = 2 in F_3.
# Elements: 0, 1, 2, α, α+1, α+2, 2α, 2α+1, 2α+2 (9 elements)
# Multiplication table: built from α² = 2.
#
# We represent an F_9 element as a pair (a, b) ∈ F_3 × F_3, where the element
# is a + b·α. Addition is componentwise mod 3. Multiplication uses α² = 2.

def f9_mult(x, y):
    """Multiply two F_9 elements (each a pair (a, b) ∈ F_3 × F_3)."""
    ax, ay = x  # a + b·α where ax = a, ay = b
    bx, by = y
    # (a + b·α)(c + d·α) = ac + (ad + bc)·α + bd·α²
    # α² = -1 = 2 in F_3, so bd·α² = 2·bd
    return ((ax * bx + 2 * ay * by) % 3,
            (ax * by + ay * bx) % 3)

def f9_add(x, y):
    return ((x[0] + y[0]) % 3, (x[1] + y[1]) % 3)

def f9_neg(x):
    return ((-x[0]) % 3, (-x[1]) % 3)

def f9_to_pair(x):
    return x  # already a pair

def f9_inv(x):
    """Inverse of x in F_9 (assuming x != 0)."""
    a, b = x
    # (a + bα)^(-1) = (a - bα) / (a² + b²)  [since α² = -1, norm = a² + b²]
    # In F_3, division by n is multiplication by n^(-1) mod 3
    norm = (a * a + 2 * b * b) % 3  # = a² + b²·α² = a² + 2·b² (in F_3)
    # Wait: norm = (a + bα)(a - bα) = a² - b²α² = a² - 2b² (in F_3, where α²=2)
    # = a² - 2b² = a² + b² (since -2 ≡ 1 mod 3)
    norm = (a * a + b * b) % 3
    if norm == 0:
        return None  # x is zero; no inverse
    # Inverse of norm in F_3: 1^(-1) = 1, 2^(-1) = 2 (since 2·2 = 4 = 1 mod 3)
    norm_inv = norm  # in F_3, the inverse of 1 is 1, the inverse of 2 is 2
    return ((a * norm_inv) % 3, ((-b * norm_inv) % 3))


