def grid_to_bits_24(grid: np.ndarray) -> int:
    bits = 0
    for v in grid.flatten():
        bits = (bits << 1) | int(v & 1)
    return bits

def measure_task(name: str, n_samples: int = 30) -> Dict[str, Any]:
    fam = TASKS[name]
    rows = []
    snap_ok_count = 0
    spin_counts = []
    uses_alpha_count = 0
    for s in range(n_samples):
        x, _, _ = fam.generate(seed=s + 1, H=4, W=6, dx=1, dy=1)
        bits = grid_to_bits_24(x)
        result = f9_spin_test(bits)
        rows.append({
            "seed": s + 1, "n_ones": result["n_ones"], "parity": result["parity"],
            "in_lattice": result["in_lattice"], "uses_alpha": result.get("uses_alpha", False),
            "spin_superposition_count": result.get("spin_superposition_count"),
        })
        if result["in_lattice"]:
            snap_ok_count += 1
            if result.get("uses_alpha"):
                uses_alpha_count += 1
            if result.get("spin_superposition_count") is not None:
                spin_counts.append(result["spin_superposition_count"])
    return {
        "task": name, "n_samples": n_samples,
        "snap_ok_count": snap_ok_count, "snap_ok_rate": snap_ok_count / n_samples,
        "uses_alpha_count": uses_alpha_count,
        "mean_spin_superpositions": float(np.mean(spin_counts)) if spin_counts else 0.0,
        "max_spin_superpositions": max(spin_counts) if spin_counts else 0,
        "rows": rows,
    }


