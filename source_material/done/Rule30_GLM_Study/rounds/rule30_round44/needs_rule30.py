def chk_H02(sc):
    N = sc["ldiag"]
    d = ldiag(N)
    return all(d["pre"][D] > D for D in range(20, N))


def chk_H03(sc):
    N = sc["ldiag"]
    d = ldiag(N)
    return all(Fraction(30, 29) <= Fraction(d["pre"][D], D) <= Fraction(71, 48) for D in range(20, N))


def chk_H16(sc):
    """No eventual period p <= 64 with preperiod <= 10000: one witness n >= 10000 per p."""
    n = sc["centre"]
    if n < 10200:
        return None
    a = centre_bits(n)
    return all(any(a[k + p] != a[k] for k in range(10000, n - p)) for p in range(1, 65))


def chk_H17(sc):
    return balance_ok(centre_bits(sc["centre"]), 9)


def chk_H19(sc):
    prof = lc_profile(sc["lc"])
    return all(abs(2 * L - (i + 1)) <= 10 for i, L in enumerate(prof))


def chk_wobble_seeds(sc):
    k = sc["seeds"]
    seeds = [1, 0b11, 0b101][:k] if k <= 3 else [1] + [(1 << j) | 1 for j in range(1, k)]
    vals = {wobble_max(centre_bits(20000, s)) for s in seeds}
    return len(vals) == 1


def chk_H36(sc):
    """'the centre column is LESS uniform than Thue-Morse' (2-bit block gaps 185 vs 10000)."""
    n = 60000
    if sc["centre"] < n:
        return None
    a = centre_bits(n)
    tm = [bin(i).count("1") % 2 for i in range(n)]

    def gap(s):
        c = [0, 0, 0, 0]
        for i in range(len(s) - 1):
            c[2 * s[i] + s[i + 1]] += 1
        return max(c) - min(c)
    g_c, g_t = gap(a), gap(tm)
    return g_c > g_t   # "less uniform" means a larger gap


def chk_LD_div(m):
    def f(sc):
        d = ldiag(sc["ldiag"])
        return all(m % p == 0 for p in d["lp"])
    return f


def chk_white_finite(sc):
    """'the eventually white left diagonals are exactly 2, 7, 28'."""
    d = ldiag(sc["ldiag"])
    return [D for D in range(sc["ldiag"]) if d["white"][D]] == [2, 7, 28]


def chk_white_alone(sc):
    """'white(D-1) alone makes diagonal D double its period'."""
    d = ldiag(sc["ldiag"])
    lp, w = d["lp"], d["white"]
    for D in range(2, sc["ldiag"]):
        if w[D - 1] and not lp[D] > max(lp[D - 1], lp[D - 2]):
            return False
    return True


def chk_words10(sc):
    n = sc["centre"]
    a = centre_bits(min(n, 20000))
    seen = set()
    for i in range(len(a) - 9):
        v = 0
        for j in range(10):
            v = 2 * v + a[i + j]
        seen.add(v)
    return True if len(seen) == 1024 else None   # absence in a prefix refutes nothing


def chk_wobble80(sc):
    if sc["centre"] < 10000:
        return None
    d, best = 0, 0
    for b in centre_bits(10000):
        d += 1 if b else -1
        best = max(best, abs(d))
    return best <= 80


def chk_parity_descends(sc):
    """'one Rule 30 step descends to row parity': rows of width <= 10."""
    def step_row(x, w):
        return (x << 2) ^ ((x << 1) | x)
    seen = {}
    for w in range(1, 11):
        for x in range(1 << w):
            par = bin(x).count("1") & 1
            nxt = bin(step_row(x, w)).count("1") & 1
            if seen.setdefault(par, nxt) != nxt:
                return False
    return True


