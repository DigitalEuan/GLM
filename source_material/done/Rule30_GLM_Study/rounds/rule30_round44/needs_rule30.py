def needs_of(tid, ctx):
    """The engine's statement of what it needs, from the task's kind only."""
    _, text, kind, obs, key, _, _ = TASK[tid]
    out = []
    if kind == "universal":
        if obs:
            out.append(Need("range", f"range:{obs}", f"'{key}' survived only the base range of '{obs}'; "
                            "a larger exact range can refute it", [tid],
                            "a refutation, or survival on the larger range"))
        out.append(Need("fact", f"fact:{key}", f"'{key}' is a statement about all indices; finite data "
                        "cannot prove it", [tid], "a Lean theorem or a refutation"))
    elif kind == "finite":
        out.append(Need("range", f"range:{obs}", f"'{key}' is a finite statement beyond the base range of "
                        f"'{obs}'", [tid], "an exact computation on the stated range"))
        out.append(Need("fact", f"fact:{key}", "a certificate would settle it", [tid], "a Lean certificate"))
    elif kind == "implication":
        out.append(Need("fact", f"fact:implication:{key}", f"'{key}' asserts that one statement follows "
                        "from another; that is a claim about all models, not about the data", [tid],
                        "a proof of the implication or a counterexample to the argument form"))
    elif kind in ("analogy", "proposal", "meta"):
        out.append(Need("test", f"test:{key}", f"'{key}' has no executable test; without one it is not "
                        "evidence of anything", [tid], "an executable test with a pass/fail outcome"))
    elif kind == "prediction":
        out.append(Need("fact", f"fact:{key}", f"'{key}' extrapolates beyond all data; it needs an "
                        "independent cross-check", [tid], "a proved law or an independent computation"))
        if obs:
            out.append(Need("range", f"range:{obs}:predicted", "the predicted index is beyond every range",
                            [tid], "a computation reaching the predicted index"))
    elif kind == "measurement":
        out.append(Need("tool", f"tool:recompute:{obs}", f"'{key}' reports a number and a comparison; "
                        "re-run both", [tid], "the recomputed number and comparison"))
    elif kind == "open":
        out.append(Need("fact", f"fact:{key}", f"'{key}' is listed as unknown; the ledger may already "
                        "settle it or an equivalent form", [tid], "a ledger entry"))
    return out


def guard(tid, ctx, value, unmet):
    """Honesty guard: a definite True without a met fact/test/range need becomes 'unknown'.
    It never changes False (refutations by data are sound) and never invents an answer."""
    if value is T and any(n.kind in ("fact", "test", "range", "tool") for n in unmet):
        kind = TASK[tid][2]
        if kind != "finite" or any(n.kind == "range" for n in unmet):
            return U
    return value


