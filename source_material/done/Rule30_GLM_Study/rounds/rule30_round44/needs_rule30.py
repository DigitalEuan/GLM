def _range_provision(obs):
    def fn(tid, ctx):
        _, _, kind, o, _, _, chk = TASK[tid]
        if o != obs or chk is None:
            return None
        v = chk(EXT)
        if v is None:
            return None
        if v is F:
            return F                      # a refutation by exact data: sound
        if kind == "finite":
            return T                      # the finite statement itself was computed: sound
        if kind == "measurement":
            return T
        return None                       # survival of a universal statement proves nothing
    return fn


def _recompute(tid, ctx):
    _, _, kind, o, _, _, chk = TASK[tid]
    if kind != "measurement" or chk is None:
        return None
    v = chk(EXT)
    return v


def _ledger(tid, ctx):
    key = TASK[tid][4]
    if key in LEDGER:
        v = LEDGER[key][0]
        return v
    return None


def _implications(tid, ctx):
    key = TASK[tid][4]
    if key in IMPLICATIONS:
        return IMPLICATIONS[key][0]
    return None


def make_wheel() -> Wheel:
    return Wheel([
        Provision("RANGE-CENTRE", ["range:centre"], _range_provision("centre"), "EXACT", True,
                  "centre column to 200 000 bits; refutes universal claims, decides finite ones"),
        Provision("TOOL-BM", ["range:lc", "tool:linear-complexity"], _range_provision("lc"), "EXACT", True,
                  "Berlekamp-Massey linear complexity to n = 20 000"),
        Provision("RANGE-LDIAG", ["range:ldiag"], _range_provision("ldiag"), "EXACT", True,
                  "left diagonals D < 20 000: periods, white set, exact transients"),
        Provision("RANGE-SEEDS", ["range:seeds"], _range_provision("seeds"), "EXACT", True,
                  "the wobble statistic on 32 seeds"),
        Provision("RECOMPUTE", ["tool:recompute:*"], _recompute, "EXACT", True,
                  "re-run a reported measurement and its comparison"),
        Provision("LEDGER", ["fact:*"], _ledger, "FORMAL/CERT", True,
                  "the Lean ledger: proved, refuted or open, with the Lean name"),
        Provision("IMPLICATIONS", ["fact:implication:*"], _implications, "FORMAL", True,
                  "checked implications and counterexamples to argument forms"),
    ])


def tasks_and_truth():
    tids = [t[0] for t in TASKS]
    truth = {t: (None if TRUTH[t][0] is None else TRUTH[t][0]) for t in tids}
    return tids, truth


def normalise(v):
    return None if v == OPEN else v
