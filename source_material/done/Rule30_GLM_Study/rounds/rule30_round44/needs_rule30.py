@lru_cache(maxsize=None)
def centre_bits(n: int, seed: int = 1) -> tuple:
    """First n centre bits; row as an integer, bit i = cell i - n - 1, one step = Rule 30."""
    mid = n + 1
    r = seed << mid
    out = []
    for _ in range(n):
        out.append((r >> mid) & 1)
        r = (r << 1) ^ (r | (r >> 1))
        r &= (1 << (2 * n + 4 + seed.bit_length())) - 1
    return tuple(out)


def wobble_max(bits) -> Fraction:
    d, best = 0, Fraction(0)
    for n, b in enumerate(bits, 1):
        d += 1 if b else -1
        v = Fraction(d * d, n)
        if v > best:
            best = v
    return best


def balance_ok(bits, c2: int) -> bool:
    """|#1 - #0| <= c * sqrt(N) for every prefix, i.e. D(N)^2 <= c^2 N (exact)."""
    d = 0
    for n, b in enumerate(bits, 1):
        d += 1 if b else -1
        if d * d > c2 * n:
            return False
    return True


@lru_cache(maxsize=None)
def lc_profile(n: int) -> tuple:
    """Berlekamp-Massey over GF(2) on the first n centre bits: L(1..n)."""
    bits = centre_bits(max(n, 1))[:n]
    rev = 0           # bit j of rev = bits[i-1-j] at step i (reversed prefix)
    C, B, L, m = 1, 1, 0, 1
    out = []
    for i in range(n):
        d = (bits[i] + ((C >> 1) & rev).bit_count()) & 1
        if d:
            Tt = C
            C ^= B << m
            if 2 * L <= i:
                L, B, m = i + 1 - L, Tt, 1
            else:
                m += 1
        else:
            m += 1
        out.append(L)
        rev = (rev << 1) | bits[i]
    return tuple(out)


@lru_cache(maxsize=None)
def ldiag(N: int, pmax: int = 64) -> dict:
    """Left diagonals D < N of the single-cell seed: least eventual period, white flag, parity,
    exact preperiod.  Row bit D = left diagonal D (left-aligned step)."""
    mask = (1 << N) - 1
    hist = [1]
    r = 1
    t = 0
    while True:
        r = ((r << 2) ^ ((r << 1) | r)) & mask
        hist.append(r)
        t += 1
        if t >= pmax and hist[t] == hist[t - pmax]:
            s = t - pmax
            break
    rows = hist[s:s + pmax]
    lp, white, parity = [], [], []
    for D in range(N):
        pat = 0
        for i, row in enumerate(rows):
            pat |= ((row >> D) & 1) << ((s + i) % pmax)
        p = pmax
        while p > 1:
            q = p // 2
            rot = ((pat >> q) | (pat << (pmax - q))) & ((1 << pmax) - 1)
            if rot != pat:
                break
            p = q
        ones = bin(pat).count("1") * p // pmax
        lp.append(p)
        white.append(pat == 0)
        parity.append(ones % 2)
    pre = [0] * N
    seen = 0
    for tt in range(s - 1, -1, -1):
        x = (hist[tt] ^ hist[tt + pmax]) & ~seen
        while x:
            low = x & -x
            pre[low.bit_length() - 1] = tt + 1
            x ^= low
        seen |= hist[tt] ^ hist[tt + pmax]
    return {"lp": lp, "white": white, "parity": parity, "pre": pre}


