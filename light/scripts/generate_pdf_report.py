# ── Heading helpers (with TOC bookmarks) ────────────────────────────────────
def heading(text, style, level=0):
    key = f'h_{hashlib.md5(text.encode()).hexdigest()[:8]}'
    p = Paragraph(f'<a name="{key}"/>{text}', style)
    p.bookmark_name = key
    p.bookmark_level = level
    p.bookmark_text = text
    p.bookmark_key = key
    return p

def h1(text): return heading(text, STYLES['h1'], 0)
def h2(text): return heading(text, STYLES['h2'], 1)


# ── Table builder ───────────────────────────────────────────────────────────
def make_table(headers, rows, col_widths=None, available_width=None):
    """Build a styled table with proper Paragraph cells."""
    if available_width is None:
        available_width = A4[0] - 4.4*cm
    if col_widths is None:
        # Equal widths
        col_widths = [available_width / len(headers)] * len(headers)
    else:
        # Normalize to available width
        total = sum(col_widths)
        col_widths = [w / total * available_width for w in col_widths]

    # Build header row
    header_row = [Paragraph(str(h), STYLES['table_header']) for h in headers]
    # Build data rows
    data = [header_row]
    for r in rows:
        cells = []
        for i, c in enumerate(r):
            if isinstance(c, (int, float)) and not isinstance(c, bool):
                # Numeric: right-aligned mono
                if abs(c) > 1e6 or (abs(c) < 1e-3 and c != 0):
                    txt = f"{c:.4e}"
                elif abs(c) > 100:
                    txt = f"{c:,.2f}"
                else:
                    txt = f"{c:.4f}"
                cells.append(Paragraph(txt, STYLES['table_cell_num']))
            else:
                cells.append(Paragraph(str(c), STYLES['table_cell']))
        data.append(cells)

    t = Table(data, colWidths=col_widths, repeatRows=1)
    style = TableStyle([
        ('BACKGROUND', (0, 0), (-1, 0), HEADER_FILL),
        ('TEXTCOLOR', (0, 0), (-1, 0), colors.white),
        ('FONTNAME', (0, 0), (-1, 0), 'DejaVuSans-Bold'),
        ('FONTSIZE', (0, 0), (-1, 0), 9.5),
        ('ALIGN', (0, 0), (-1, 0), 'LEFT'),
        ('VALIGN', (0, 0), (-1, -1), 'MIDDLE'),
        ('FONTNAME', (0, 1), (-1, -1), 'DejaVuSans'),
        ('FONTSIZE', (0, 1), (-1, -1), 9),
        ('ROWBACKGROUNDS', (0, 1), (-1, -1), [colors.white, TABLE_STRIPE]),
        ('GRID', (0, 0), (-1, -1), 0.25, BORDER),
        ('TOPPADDING', (0, 0), (-1, -1), 5),
        ('BOTTOMPADDING', (0, 0), (-1, -1), 5),
        ('LEFTPADDING', (0, 0), (-1, -1), 6),
        ('RIGHTPADDING', (0, 0), (-1, -1), 6),
    ])
    t.setStyle(style)
    return t


