class TocDocTemplate(BaseDocTemplate):
    """SimpleDocTemplate subclass that captures TOC entries."""
    def __init__(self, filename, **kw):
        BaseDocTemplate.__init__(self, filename, **kw)
        # Single frame for body content
        frame = Frame(2.2*cm, 2.0*cm, A4[0] - 4.4*cm, A4[1] - 4.0*cm,
                      leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0,
                      id='body_frame')
        # Cover template (no header)
        cover_frame = Frame(2.2*cm, 2.0*cm, A4[0] - 4.4*cm, A4[1] - 4.0*cm,
                            leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0,
                            id='cover_frame')
        self.addPageTemplates([
            PageTemplate(id='Cover', frames=[cover_frame]),
            PageTemplate(id='Body', frames=[frame], onPage=draw_page_decorations),
        ])

    def afterFlowable(self, flowable):
        if hasattr(flowable, 'bookmark_name'):
            level = getattr(flowable, 'bookmark_level', 0)
            text = getattr(flowable, 'bookmark_text', '')
            key = getattr(flowable, 'bookmark_key', '')
            self.notify('TOCEntry', (level, text, self.page, key))


