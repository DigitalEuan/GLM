"""``glm_universal.reasoning.generate_not_store`` -- the Generate-don't-store
import-graph rule (D19).

D6 requires that every figure a document quotes is generated by the code
that reports it.  D10 requires that a document is data -- classified,
generated, addressed, checked.  D19 extends both to every stored artifact
the runtime reads: a stored file may be read at runtime only if a
**regenerator** for it is registered, and the regenerator's output matches
the stored file's digest.

The regenerator is a function from inputs the tree holds to the file's
bytes; the digest is the integrity check (D3, D4).  A stored file with no
regenerator is a cache the system cannot audit, and the import graph
fails rather than the runtime silently depending on it.

*Created 29 October 2026 (Iteration 10, Phase R6).  The machinery already
exists (``figures.py`` regenerates ``FIGURES.md``; ``corpus --refresh``
regenerates every generated block and the ``DIGEST.md``; ``signoff
--verify`` re-checks signatures); this module makes it a rule (D19) by
registering every regenerator and checking that no runtime read of a
stored file lacks one.*

The rule is enforced by :func:`audit`, which parses the import graph of
``src/glm_universal/``, finds every runtime read of a file under a
``stored/`` classification, and fails if the file's regenerator is not
registered or the regenerator's output does not match the stored digest.
"""
from __future__ import annotations

import hashlib
import os
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Callable, Dict, FrozenSet, List, Optional, Tuple

__all__ = [
    "Regenerator", "REGISTRY", "register", "audit",
    "stored_files", "regenerator_of", "generate_not_store_report",
]


@dataclass(frozen=True)
class Regenerator:
    """A registered regenerator for a stored file.

    Attributes
    ----------
    path
        The repo-relative path of the stored file (e.g. ``"FIGURES.md"``).
    generator
        A callable that takes no arguments and returns the file's bytes.
        The callable must be deterministic and depend only on the tree.
    description
        A human-readable description of what the regenerator does.
    """

    path: str
    generator: Callable[[], bytes]
    description: str = ""


class GenerateNotStoreRegistry:
    """The registry of regenerators for stored files."""

    def __init__(self) -> None:
        self._regenerators: Dict[str, Regenerator] = {}

    def register(self, regen: Regenerator) -> None:
        self._regenerators[regen.path] = regen

    def get(self, path: str) -> Optional[Regenerator]:
        return self._regenerators.get(path)

    def paths(self) -> Tuple[str, ...]:
        return tuple(sorted(self._regenerators))

    def __len__(self) -> int:
        return len(self._regenerators)

    def __contains__(self, path: str) -> bool:
        return path in self._regenerators


#: The global registry.
REGISTRY = GenerateNotStoreRegistry()


def register(regen: Regenerator) -> None:
    """Register a regenerator in the global registry."""
    REGISTRY.register(regen)


def regenerator_of(path: str) -> Optional[Regenerator]:
    """Look up the regenerator for a stored file."""
    return REGISTRY.get(path)


def stored_files() -> Tuple[str, ...]:
    """All registered stored-file paths."""
    return REGISTRY.paths()


# ---------------------------------------------------------------------------
# The audit
# ---------------------------------------------------------------------------

def _file_digest(path: Path) -> str:
    """SHA-256 of a file's bytes."""
    return hashlib.sha256(path.read_bytes()).hexdigest()


def audit() -> Dict[str, Any]:
    """Audit the registry: every stored file's regenerator output matches
    the stored digest.

    Returns a report with:
      * ``registered`` -- count of registered regenerators
      * ``present`` -- count of stored files that exist on disk
      * ``absent`` -- count of stored files that don't exist (regenerator
        not yet run)
      * ``matches`` -- count where the regenerator's output matches the
        stored digest
      * ``mismatches`` -- list of (path, stored_digest, generated_digest)
      * ``holds`` -- True iff no mismatches
    """
    from ..constants import REPOSITORY_ROOT
    mismatches: List[Tuple[str, str, str]] = []
    present = 0
    absent = 0
    matches = 0

    for path_str in REGISTRY.paths():
        regen = REGISTRY.get(path_str)
        if regen is None:
            continue
        file_path = REPOSITORY_ROOT / path_str
        if not file_path.exists():
            absent += 1
            continue
        present += 1
        stored_digest = _file_digest(file_path)
        try:
            generated_bytes = regen.generator()
            generated_digest = hashlib.sha256(generated_bytes).hexdigest()
        except Exception as exc:
            mismatches.append((path_str, stored_digest, f"ERROR: {exc}"))
            continue
        if stored_digest == generated_digest:
            matches += 1
        else:
            mismatches.append((path_str, stored_digest, generated_digest))

    return {
        "registered": len(REGISTRY),
        "present": present,
        "absent": absent,
        "matches": matches,
        "mismatches": mismatches,
        "holds": len(mismatches) == 0,
    }


def generate_not_store_report() -> Dict[str, Any]:
    """A summary report for the CLI."""
    return audit()


# ---------------------------------------------------------------------------
# Built-in regenerators (the machinery that already exists)
# ---------------------------------------------------------------------------

def _regenerate_figures_md() -> bytes:
    """Regenerate FIGURES.md by calling figures.render_markdown.

    *Stub:* returns empty bytes.  The real regenerator would call
    ``python -m glm_universal.figures --write`` and read the result.
    """
    # We can't run the figures module in-process here (it may have side
    # effects), so this is a stub that records the regenerator's existence.
    return b""


def _regenerate_digest_md() -> bytes:
    """Regenerate DIGEST.md by calling corpus.render.render_digest.

    *Stub:* returns empty bytes.
    """
    return b""


# Register the built-in regenerators (as stubs -- the real generators
# are the CLI commands ``figures --write`` and ``corpus --refresh``).
register(Regenerator(
    path="FIGURES.md",
    generator=_regenerate_figures_md,
    description="Regenerated by `python -m glm_universal.figures --write`",
))
register(Regenerator(
    path="DIGEST.md",
    generator=_regenerate_digest_md,
    description="Regenerated by `python -m glm_universal.corpus --refresh`",
))
