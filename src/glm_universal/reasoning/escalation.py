def _register_loader(register: str) -> Callable[[], Sequence]:
    from ..data_objects import (element_objects, harmonic_objects,
                                mathematics_objects, molecule_objects,
                                physics_objects, semantic_lexicon_objects)
    if register == "physics":
        return physics_objects
    if register == "chemistry":
        return element_objects
    if register == "molecules":
        return molecule_objects
    if register == "mathematics":
        return mathematics_objects
    if register == "harmonics":
        return harmonic_objects
    if register == "lexicon":
        return lambda: semantic_lexicon_objects()[0]
    raise KeyError(f"escalation: no loader for register {register!r}")


#: Register carrier sets already built, keyed by the registers asked for.
#: Loading the six registers parses several data files; the study asks for
#: them repeatedly and they never change within a process.
_CARRIER_CACHE: Dict[Tuple[str, ...], Tuple["RegisterCarrier", ...]] = {}


def register_carriers(registers: Sequence[str] = REGISTERS
                      ) -> Tuple[RegisterCarrier, ...]:
    """One carrier per named object of each register, in register order.

    This is the carrier set the study runs on: not chosen, not sampled, and
    not made up -- it is simply everything the machine holds.
    """
    cached = _CARRIER_CACHE.get(tuple(registers))
    if cached is not None:
        return cached
    out: List[RegisterCarrier] = []
    for register in registers:
        for obj in _register_loader(register)():
            out.append(RegisterCarrier(
                register=register, name=obj.name,
                carrier=tuple(Fraction(x) for x in obj.carrier)))
    _CARRIER_CACHE[tuple(registers)] = tuple(out)
    return _CARRIER_CACHE[tuple(registers)]


def by_register(entries: Sequence[RegisterCarrier]) -> List[Dict[str, object]]:
    """The same audit register by register, so the ceiling can be attributed.

    The whole-corpus figures say how far escalation reaches; these say where
    what it does not reach comes from.  Each row is computed on that
    register's entries alone, so the rows need not sum to the whole -- two
    registers could in principle share a carrier, and ``cross_register`` in
    the ceiling is what says whether any do.
    """
    groups: Dict[str, List[RegisterCarrier]] = {}
    for entry in entries:
        groups.setdefault(entry.register, []).append(entry)
    out: List[Dict[str, object]] = []
    for register in REGISTERS:
        group = groups.get(register)
        if not group:
            continue
        carriers = [e.carrier for e in group]
        distinct = len(set(carriers))
        out.append({
            "register": register,
            "entries": len(group),
            "substrate": keyed_resolution("substrate", carriers),
            "integer": keyed_resolution("integer", carriers),
            "distinct_carriers": distinct,
            "unreachable": len(group) - distinct,
        })
    return out


def register_sizes(entries: Sequence[RegisterCarrier]) -> Dict[str, int]:
    """How many entries each register contributed."""
    sizes: Dict[str, int] = {}
    for entry in entries:
        sizes[entry.register] = sizes.get(entry.register, 0) + 1
    return sizes


def verification_sample(entries: Sequence[RegisterCarrier],
                        per_register: int = VERIFY_PER_REGISTER
                        ) -> Tuple[RegisterCarrier, ...]:
    """A small, evenly spread, deterministic slice of the registers.

    Evenly spread rather than the first few, so the sample is not all of one
    domain, and index-based rather than random, so it is the same sample in
    every interpreter.
    """
    by_register: Dict[str, List[RegisterCarrier]] = {}
    for entry in entries:
        by_register.setdefault(entry.register, []).append(entry)
    out: List[RegisterCarrier] = []
    for register in REGISTERS:
        group = by_register.get(register, [])
        if not group:
            continue
        take = min(per_register, len(group))
        for k in range(take):
            out.append(group[(k * len(group)) // take])
    return tuple(out)


def key_agreement(entries: Sequence[RegisterCarrier]) -> Dict[str, object]:
    """Re-derive the keys from the layers themselves, the slow way.

    For every pair of the sample and every layer, the layer's own ``perceive``
    and ``measure`` are run and their verdict compared with the keys'.  A
    single disagreement makes ``agrees`` false and names the pair, and the
    report carries that field, so the fast path can never be quietly wrong.
    """
    carriers = [e.carrier for e in entries]
    layers = list(DL.LAYERS) + [DL.LAYER_INTEGER_RAW]
    checked = 0
    disagreements: List[Dict[str, object]] = []
    for layer in layers:
        for i in range(len(carriers)):
            for j in range(i + 1, len(carriers)):
                by_measure = IL.indistinguishable(layer, carriers[i],
                                                  carriers[j])
                by_key = (class_key(layer.name, carriers[i])
                          == class_key(layer.name, carriers[j]))
                checked += 1
                if by_measure != by_key:
                    disagreements.append({
                        "layer": layer.name,
                        "a": entries[i].name, "b": entries[j].name,
                        "by_measure": by_measure, "by_key": by_key})
    return {
        "sample_size": len(entries),
        "sample_names": [e.name for e in entries],
        "layers": [layer.name for layer in layers],
        "pairs_checked": checked,
        "agrees": not disagreements,
        "disagreements": disagreements,
    }


