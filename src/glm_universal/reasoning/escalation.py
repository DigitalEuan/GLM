"""``glm_universal.reasoning.escalation`` -- the layer stack at register scale.

What this module is
-------------------
:mod:`~glm_universal.reasoning.information_loss` measures the five-layer stack
on **seven** hand-picked carriers, each chosen to exhibit one boundary.  That
answers *does each boundary exist*.  It does not answer the question the layer
work left open: *what does escalation look like when the carrier set is the
machine's own data* -- a thousand real carriers that nobody chose to make a
point.

This module answers that one.  It draws one carrier per named object from every
register the package ships and runs the same audit over the lot.

Why it can afford to
--------------------
The audit in ``information_loss`` compares carriers **pairwise**: its
``classes`` is quadratic and its ``congruence_witness`` quartic, and each
comparison may run a Leech nearest-point decode.  At 1,040 carriers that is not
a slow computation, it is an impossible one.

The way out is not an approximation.  Each layer's ``measure`` is a sum of
non-negative exact terms, and it is zero exactly when a small, cheap *reading*
of the two carriers agrees -- that reading is the layer's **class key**:

===============  ==========================================================
layer            zero-measure key, and why it is the key
===============  ==========================================================
``substrate``    the 24 parity bits.  ``_substrate_measure`` is the Hamming
                 distance between them, zero iff they are equal.
``integer``      the seven SI7 exponents **and** the parity bits.
                 ``_integer_measure`` is an L1 term plus a Hamming term,
                 both non-negative, so the sum is zero iff each is.
``rational``     the exact carrier.  ``_rational_measure`` is
                 ``metric.distance2``, which is positive definite over ℚ.
``griess``       the exact carrier again: the measure is the algebraic
                 distance *plus* ``distance2``, both non-negative, and equal
                 carriers force equal algebra elements.
``universal``    likewise the exact carrier.
``integer_raw``  the seven SI7 exponents alone -- the rejected reading, kept
                 so its cost can be measured at scale too.
===============  ==========================================================

Keys are hashable, so every quantity the study needs -- resolution, loss,
boundary sizes, refinement violations -- is computed by grouping rather than by
comparing, in time linear in the carrier count.

That the keys really are the zero sets is not asserted: :func:`key_agreement`
re-runs the layers' own ``perceive`` and ``measure`` over every pair of a
deterministic subsample and fails if ``measure == 0`` and ``key equality`` ever
disagree, and the report carries the result.  The same identification is what
``RequestProject/GLM/LayerChain.lean`` already models -- a layer there *is* its
view map -- and ``RequestProject/GLM/Escalation.lean`` proves the two facts this
study turns on: that resolution can only rise as the stack is climbed, whatever
the carrier set, and that two register entries carrying the same 24 coordinates
are separated by no layer of the stack at all.

Everything is exact.  No float is constructed anywhere in this module.
"""

