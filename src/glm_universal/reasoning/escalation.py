#: The registers the study draws from, in a fixed order.  ``spatial`` is not
#: here: it is generated by the runtime rather than shipped as data, and this
#: module stays inside the reasoning layer.
REGISTERS: Tuple[str, ...] = (
    "physics", "chemistry", "molecules", "mathematics", "harmonics", "lexicon",
)

#: How many carriers per register the key-agreement check re-derives the slow
#: way.  Every pair of the sample is checked at every layer.
VERIFY_PER_REGISTER: int = 3

#: The layers this module keys, lowest first, with the rejected reading last.
KEYED_LAYERS: Tuple[str, ...] = (
    "substrate", "integer", "rational", "griess", "universal", "integer_raw",
)

#: Why each key is exactly the layer's zero-measure reading.  Quoted by the
#: report so the justification travels with the numbers.
KEY_JUSTIFICATION: Dict[str, str] = {
    "substrate":
        "Hamming distance between the 24 parity bits; zero iff the bits are "
        "equal.",
    "integer":
        "an L1 term on the seven SI7 exponents plus a Hamming term on the "
        "parity bits, both non-negative, so zero iff both readings agree.",
    "rational":
        "metric.distance2 on the exact carriers, positive definite over the "
        "rationals, so zero iff the carriers are equal.",
    "griess":
        "the algebraic distance plus distance2 on the carriers, both "
        "non-negative; equal carriers also force equal algebra elements.",
    "universal":
        "the same measure as the Griess layer, so the same key.",
    "integer_raw":
        "an L1 term on the seven SI7 exponents alone; zero iff they agree.",
}


@dataclass(frozen=True)
class RegisterCarrier:
    """One named object of one register, as an exact 24-coordinate carrier."""

    register: str
    name: str
    carrier: Tuple[Fraction, ...]


# ===========================================================================
# 1.  THE KEYS
# ===========================================================================

def _si7(carrier: Sequence) -> Tuple[int, ...]:
    """The seven SI7 exponents, read exactly as ``_integer_perceive`` reads them.

    Only the first seven coordinates are converted: the reading does not look
    at the other seventeen, and this function is called a few hundred thousand
    times by the congruence search.
    """
    return (int(carrier[0]), int(carrier[1]), int(carrier[2]),
            int(carrier[3]), int(carrier[4]), int(carrier[5]),
            int(carrier[6]))


def class_key(layer_name: str, carrier: Sequence) -> Hashable:
    """The reading whose equality is the layer's ``measure == 0``.

    See the module docstring for the argument, and :func:`key_agreement` for
    the check that re-derives it from the layers themselves.
    """
    if layer_name == "substrate":
        return DL.parity_bits(carrier)
    if layer_name == "integer":
        return (_si7(carrier), DL.parity_bits(carrier))
    if layer_name == "integer_raw":
        return _si7(carrier)
    if layer_name in ("rational", "griess", "universal"):
        return tuple(Fraction(x) for x in carrier)
    raise KeyError(f"escalation: no class key for layer {layer_name!r}")


def keyed_classes(layer_name: str,
                  carriers: Sequence[Sequence]) -> Tuple[Tuple[int, ...], ...]:
    """Partition indices into the classes the layer resolves, by key.

    Classes come out in first-appearance order, so the result is a
    deterministic function of the carrier order -- exactly like
    :func:`glm_universal.reasoning.information_loss.classes`, which it agrees
    with wherever both can be run.
    """
    order: List[Hashable] = []
    buckets: Dict[Hashable, List[int]] = {}
    for i, carrier in enumerate(carriers):
        k = class_key(layer_name, carrier)
        if k not in buckets:
            buckets[k] = []
            order.append(k)
        buckets[k].append(i)
    return tuple(tuple(buckets[k]) for k in order)


def keyed_resolution(layer_name: str, carriers: Sequence[Sequence]) -> int:
    """How many distinct things the layer resolves among these carriers."""
    return len(keyed_classes(layer_name, carriers))


def keyed_loss(layer_name: str, carriers: Sequence[Sequence]) -> int:
    """How many carriers the layer loses: the count minus what it resolves."""
    return len(carriers) - keyed_resolution(layer_name, carriers)


# ===========================================================================
# 2.  BOUNDARIES, COUNTED RATHER THAN LISTED
# ===========================================================================

def _pairs(n: int) -> int:
    """``n`` choose 2, the number of unordered pairs inside a class."""
    return n * (n - 1) // 2


def pair_counts(lower: str, higher: str,
                carriers: Sequence[Sequence]) -> Dict[str, int]:
    """Conflated-pair counts for two layers and for both at once.

    Every quantity the boundary needs follows from three numbers -- the pairs
    the lower layer conflates, the pairs the higher one conflates, and the
    pairs *both* conflate -- and each is a sum over the classes of one
    partition, so none of them costs a pair-by-pair scan.
    """
    low = sum(_pairs(len(c)) for c in keyed_classes(lower, carriers))
    high = sum(_pairs(len(c)) for c in keyed_classes(higher, carriers))
    joint: Dict[Tuple[Hashable, Hashable], int] = {}
    for carrier in carriers:
        k = (class_key(lower, carrier), class_key(higher, carrier))
        joint[k] = joint.get(k, 0) + 1
    both = sum(_pairs(n) for n in joint.values())
    return {"lower": low, "higher": high, "both": both}


def boundary_at_scale(lower: str, higher: str,
                      carriers: Sequence[Sequence]) -> Dict[str, object]:
    """What the step from ``lower`` to ``higher`` gains, and what it costs.

    ``gained`` is the size of the boundary -- pairs the lower layer conflates
    and the higher one splits.  ``violations`` is its mirror image: pairs the
    lower layer splits and the higher one conflates, which is the escalation
    ladder losing something it already had.  A step is a refinement exactly
    when ``violations`` is zero.
    """
    counts = pair_counts(lower, higher, carriers)
    gained = counts["lower"] - counts["both"]
    violations = counts["higher"] - counts["both"]
    example = None
    if violations:
        example = _first_violating_pair(lower, higher, carriers)
    return {
        "lower": lower,
        "higher": higher,
        "lower_conflated": counts["lower"],
        "higher_conflated": counts["higher"],
        "gained": gained,
        "violations": violations,
        "refines": violations == 0,
        "example_violation": example,
    }


def _first_violating_pair(lower: str, higher: str,
                          carriers: Sequence[Sequence]
                          ) -> Optional[Tuple[int, int]]:
    """The first pair, in index order, the higher layer conflates and the lower splits."""
    seen: Dict[Hashable, List[int]] = {}
    for j, carrier in enumerate(carriers):
        hk = class_key(higher, carrier)
        lk = class_key(lower, carrier)
        for i in seen.get(hk, ()):
            if class_key(lower, carriers[i]) != lk:
                return (i, j)
        seen.setdefault(hk, []).append(j)
    return None


def refines_at_scale(lower: str, higher: str,
                     carriers: Sequence[Sequence]) -> bool:
    """Whether the higher layer sees at least as much as the lower one here."""
    return boundary_at_scale(lower, higher, carriers)["violations"] == 0


# ===========================================================================
# 3.  DOES ADDITION STILL DESCEND AT SCALE?
# ===========================================================================

#: The layers whose class key *is* the carrier.  Their kernel is equality, so
#: every operation descends to them and no search can find a witness -- see
#: ``GLM.Info.glmRationalLayer_congruentOn`` in
#: ``RequestProject/GLM/Escalation.lean``.  The search is still available for
#: them through ``exhaustive=True``, and a test runs it.
CARRIER_KEYED: Tuple[str, ...] = ("rational", "griess", "universal")


def congruence_witness_at_scale(layer_name: str,
                                carriers: Sequence[Sequence],
                                exhaustive: bool = False
                                ) -> Optional[Dict[str, object]]:
    """Three indices showing that coordinatewise addition escapes the layer.

    ``a`` and ``a2`` are indistinguishable at the layer, yet ``a + b`` and
    ``a2 + b`` are not, so the layer cannot compute the sum from what it sees.
    The witness returned is the first in ``(b, class, member)`` order, so it
    is a deterministic function of the carrier set; the search itself is
    exhaustive over every such triple.
    Taking ``b`` on both sides is no loss of generality: if some quadruple
    ``a ~ a2``, ``b ~ b2`` has ``op(a, b) !~ op(a2, b2)``, then one of the two
    steps ``op(a, b) -> op(a2, b) -> op(a2, b2)`` already differs, and each of
    those is a witness of this shape.

    ``None`` means no witness exists among these carriers.  For the three
    upper layers that is a theorem rather than a search result -- their key is
    the carrier itself, so indistinguishable carriers are *equal* and have
    equal sums -- and the search is skipped unless ``exhaustive`` asks for it.
    """
    if layer_name in CARRIER_KEYED and not exhaustive:
        return None
    pairs = [(cls[0], idx)
             for cls in keyed_classes(layer_name, carriers)
             for idx in cls[1:]]
    for j, b in enumerate(carriers):
        for i, k in pairs:
            left = class_key(layer_name, IL.carrier_sum(carriers[i], b))
            right = class_key(layer_name, IL.carrier_sum(carriers[k], b))
            if left != right:
                return {"layer": layer_name, "a": i, "a2": k, "b": j}
    return None


# ===========================================================================
# 4.  THE CEILING
# ===========================================================================

def resolution_ceiling(entries: Sequence[RegisterCarrier]) -> Dict[str, object]:
    """The named objects no layer of the stack can tell apart, and why.

    Every layer's view is a function of the carrier, so two entries carrying
    the same 24 coordinates are indistinguishable at *every* layer -- the top
    of the stack included.  The number of distinct carriers is therefore a
    hard ceiling on what escalation can ever resolve, and this function
    measures how far the registers sit below it.
    """
    groups: Dict[Tuple[Fraction, ...], List[int]] = {}
    for i, entry in enumerate(entries):
        groups.setdefault(entry.carrier, []).append(i)
    collisions = [g for g in groups.values() if len(g) > 1]
    collisions.sort(key=lambda g: (-len(g), g[0]))
    within = sum(1 for g in collisions
                 if len({entries[i].register for i in g}) == 1)
    largest = collisions[0] if collisions else []
    return {
        "entries": len(entries),
        "distinct_carriers": len(groups),
        "unreachable": len(entries) - len(groups),
        "collision_classes": len(collisions),
        "within_register": within,
        "cross_register": len(collisions) - within,
        "largest_class_size": len(largest),
        "largest_class_register": entries[largest[0]].register if largest
                                   else None,
        "largest_class_examples": [entries[i].name for i in largest[:6]],
        "examples": [
            {
                "size": len(g),
                "register": entries[g[0]].register,
                "names": [entries[i].name for i in g[:4]],
            }
            for g in collisions[:4]
        ],
    }


