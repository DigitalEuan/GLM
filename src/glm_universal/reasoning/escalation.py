# 6.  THE REPORT
# ===========================================================================

def escalation_report(entries: Optional[Sequence[RegisterCarrier]] = None
                      ) -> Dict[str, object]:
    """The whole study, recomputed.  Every number here is computed.

    Nothing in it is quoted from a document, and nothing is sampled except the
    key-agreement check, whose sample is fixed by index.

    Over the default carrier set the report is a derivation of frozen
    registers, so it is computed once per process and reused;
    ``default_escalation_report.__wrapped__()`` recomputes it from scratch,
    which is what a test that wants to prove the reuse changes nothing calls.
    Passing ``entries`` always recomputes.
    """
    if entries is None:
        return default_escalation_report()
    return _escalation_report(entries)


@memo
def default_escalation_report() -> Dict[str, object]:
    """The study over every carrier the machine holds."""
    return _escalation_report(register_carriers())


def _escalation_report(entries: Sequence[RegisterCarrier]
                       ) -> Dict[str, object]:
    """Do the work :func:`escalation_report` describes, reusing nothing."""
    carriers = [e.carrier for e in entries]
    stack = ("substrate", "integer", "rational", "griess", "universal")

    layers = []
    for name in KEYED_LAYERS:
        witness = congruence_witness_at_scale(name, carriers)
        if witness is not None:
            witness = dict(witness)
            witness["names"] = [entries[witness[k]].name
                                for k in ("a", "a2", "b")]
        layers.append({
            "name": name,
            "resolution": keyed_resolution(name, carriers),
            "loss_count": keyed_loss(name, carriers),
            "largest_class": max(
                (len(c) for c in keyed_classes(name, carriers)), default=0),
            "addition_descends": witness is None,
            "congruence_witness": witness,
            "key": KEY_JUSTIFICATION[name],
        })

    boundaries = [boundary_at_scale(lo, hi, carriers)
                  for lo, hi in zip(stack, stack[1:])]

    raw = boundary_at_scale("substrate", "integer_raw", carriers)
    fixed = boundary_at_scale("substrate", "integer", carriers)

    return {
        "registers": list(REGISTERS),
        "register_sizes": register_sizes(entries),
        "by_register": by_register(entries),
        "carrier_count": len(entries),
        "layers": layers,
        "boundaries": boundaries,
        "refinement_chain_intact": all(b["refines"] for b in boundaries),
        "ceiling": resolution_ceiling(entries),
        "non_cumulative": {
            "layer": "integer_raw",
            "resolution": keyed_resolution("integer_raw", carriers),
            "loss_count": keyed_loss("integer_raw", carriers),
            "refines_substrate": raw["refines"],
            "violations": raw["violations"],
            "example_violation": raw["example_violation"],
            "example_violation_names":
                [entries[i].name for i in raw["example_violation"]]
                if raw["example_violation"] else None,
            "cumulative_refines_substrate": fixed["refines"],
            "cumulative_resolution": keyed_resolution("integer", carriers),
        },
        "key_agreement": key_agreement(verification_sample(entries)),
    }
