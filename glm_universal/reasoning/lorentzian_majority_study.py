"""``glm_universal.reasoning.lorentzian_majority_study`` -- the marks of
``studies/LORENTZIAN_MAJORITY_STUDY.md`` (Phase 184): the declared majority
rule for conflicting evidence, and its soundness condition.

*Created 23 October 2026.*

What is measured
----------------
Phase 183's physics-relation surface (``lorentzian_evidence_study.physics``):
a relation is a displacement of EXT10 exponents taken from the curated
physics analogies, its examples are register pairs stating it, a query
applies it to a register quantity ``c``, 300 queries per condition, and a
query is right when the answer is the dimension class ``exps(c) + d`` (a
query whose class is not in the register should be refused).

A condition is ``(good, colluding, independent)``: ``good`` examples of the
relation, ``colluding`` decoys that all state *one* wrong relation, and
``independent`` decoys each stating a different wrong relation (distinct from
each other and from the colluding one).

* ``clean1``, ``clean2``, ``clean3`` -- ``(1|2|3, 0, 0)``;
* ``decoy2`` ``(1, 0, 1)`` and ``decoy3`` ``(2, 0, 1)`` -- Phase 183's
  conditions, generated by the same seed and the same calls, so its figures
  must come back;
* ``decoy4`` ``(2, 0, 2)`` -- the honest examples exactly half;
* ``decoy5`` ``(3, 0, 2)`` -- the honest examples three of five;
* ``collude3`` ``(1, 2, 0)`` -- below half, the decoys agreeing;
* ``collude5`` ``(1, 2, 2)`` -- below half, the largest group the colluding
  pair (two of five).

Three rules: ``guarded`` (Phase 183's dispersion guard, refuse unless every
target agrees), ``vote`` (Phase 183's plurality: a unique most-stated target)
and ``majority`` (the declared rule, ``lorentzian_majority.relation_majority``:
a target stated by strictly more than half of the examples).

Marks, declared before the measurement was taken
------------------------------------------------
* **M1** on every condition where the honest examples are a strict majority
  (``clean1``-``clean3``, ``decoy3``, ``decoy5``) ``majority`` is never wrong,
  is right on every query whose target is in the register and refuses the
  rest (``majority_sound``).
* **M2** where the honest examples are exactly half (``decoy2``, ``decoy4``)
  ``majority`` is never wrong (``majority_never_wrong``).
* **M3** ``majority`` is right at least as often as ``guarded`` on every
  condition, and strictly more often on ``decoy3`` and ``decoy5``.
* **M4** on ``decoy3`` ``majority`` is right exactly 155 times, Phase 183's
  vote figure (the same queries, and there the two rules coincide).
* **M5** on ``collude3`` ``majority`` is wrong on exactly the queries whose
  colluding target is in the register, at least once (``majority_misled``:
  the condition is tight).
* **M6** on ``collude5`` ``majority`` refuses all 300 queries, and ``vote``
  is wrong at least once.
* **M7** on 300 random weighted target sets the rule agrees with its
  definition (answers ``v`` exactly when ``W < 2 W_v``), never answers
  anything but the planted target when that target holds at least half the
  weight, answers the common target whenever the dispersion is 0, and every
  wrong answer has decoys weighing at least its own group.
* **L** the Lean file states the quoted theorems with no ``sorry`` and is in
  the whole-development audit.
"""

