def identities() -> Dict[str, int]:
    """The rule against its definition and theorems on random weighted target
    sets: points of a small grid, weights in ``{0, 1/2, 1, 2, 3}``, one target
    planted with a random share."""
    rng = random.Random(f"{SEED}:majority:identities")
    out = {"checked": 0, "definition": 0, "never_wrong_cases": 0,
           "never_wrong": 0, "guard_cases": 0, "extends_guard": 0,
           "wrong_answers": 0, "wrong_needs_decoys": 0}
    grid = [(F(a), F(b)) for a in range(-1, 2) for b in range(-1, 2)]
    for _ in range(300):
        k = rng.randrange(1, 8)
        planted = grid[rng.randrange(len(grid))]
        targets = [planted if rng.randrange(3) else grid[rng.randrange(
            len(grid))] for _ in range(k)]
        weights = [rng.choice((F(0), F(1, 2), F(1), F(2), F(3)))
                   for _ in range(k)]
        if sum(weights) == 0:
            weights[0] = F(1)
        m = lm.majority(targets, weights)
        W = sum(weights, F(0))
        out["checked"] += 1
        brute = {v for v in set(targets)
                 if W < 2 * sum((w for t, w in zip(targets, weights)
                                 if t == v), F(0))}
        out["definition"] += (brute == ({m["value"]} if m["value"] is not None
                                        else set()))
        wd = sum((w for t, w in zip(targets, weights) if t == planted), F(0))
        if W <= 2 * wd:
            out["never_wrong_cases"] += 1
            out["never_wrong"] += m["value"] in (None, planted)
        pos = [(t, w) for t, w in zip(targets, weights) if w > 0]
        if all(t == pos[0][0] for t, _ in pos):
            out["guard_cases"] += 1
            disp = le.dispersion([(t, w) for t, w in pos])
            out["extends_guard"] += (disp == 0 and m["value"] == pos[0][0])
        if m["value"] is not None and m["value"] != planted:
            out["wrong_answers"] += 1
            decoys = W - wd
            out["wrong_needs_decoys"] += decoys >= m["decoys_needed"]
    return out


