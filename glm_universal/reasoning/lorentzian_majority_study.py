def _lean_ok() -> bool:
    root = Path(__file__).resolve().parents[2] / "glm_lean"
    text = (root / lm.LEAN_FILE).read_text(encoding="utf-8")
    audit = (root / "RequestProject" / "GLM" / "AxiomAuditAll.lean").read_text(
        encoding="utf-8")
    return ("sorry" not in text
            and all(f"theorem {t}" in text for t in lm.LEAN_THEOREMS)
            and "import RequestProject.GLM.LorentzianMajority" in audit)


def compute() -> Dict[str, object]:
    phy = physics()
    ide = identities()
    mj = {c: phy[c]["majority"] for c in CONDITIONS}
    marks = {
        "M1": all(mj[c]["wrong"] == 0 and mj[c]["right"] == phy[c]["present"]
                  and mj[c]["refused"] == phy[c]["absent"]
                  for c in HONEST_MAJORITY),
        "M2": all(mj[c]["wrong"] == 0 for c in HONEST_HALF),
        "M3": (all(mj[c]["right"] >= phy[c]["guarded"]["right"]
                   for c in CONDITIONS)
               and all(mj[c]["right"] > phy[c]["guarded"]["right"]
                       for c in ("decoy3", "decoy5"))),
        "M4": mj["decoy3"]["right"] == 155,
        "M5": (mj["collude3"]["wrong"] == phy["collude3"]["colluding_present"]
               and mj["collude3"]["wrong"] > 0),
        "M6": (mj["collude5"]["refused"] == QUERIES
               and phy["collude5"]["vote"]["wrong"] > 0),
        "M7": (ide["definition"] == ide["checked"]
               and ide["never_wrong"] == ide["never_wrong_cases"]
               and ide["extends_guard"] == ide["guard_cases"]
               and ide["wrong_needs_decoys"] == ide["wrong_answers"]),
        "L": _lean_ok(),
    }
    return {"physics": phy, "identities": ide, "marks": marks,
            "met": sum(marks.values()), "taken": len(marks)}


def _plain(x):
    if isinstance(x, Fraction):
        return str(x)
    if isinstance(x, dict):
        return {str(k): _plain(v) for k, v in x.items()}
    if isinstance(x, (list, tuple)):
        return [_plain(v) for v in x]
    return x


def module_digest() -> str:
    root = Path(__file__).resolve().parent.parent
    return integrity.tree_digest([root / n for n in sorted(set(_SOURCES))],
                                 root)


def measure() -> Dict[str, object]:
    report = compute()
    report["source_digest"] = module_digest()
    return report


def write_measurements(path: Optional[Path] = None) -> Path:
    target = Path(path) if path is not None else DATA_PATH
    target.write_text(json.dumps(_plain(measure()), indent=1, sort_keys=True,
                                 ensure_ascii=False) + "\n", encoding="utf-8")
    global _cache
    _cache = None
    return target


_cache: Optional[Dict[str, object]] = None


def measurements(refresh: bool = False) -> Optional[Dict[str, object]]:
    global _cache
    if _cache is not None and not refresh:
        return _cache
    if not DATA_PATH.exists():
        return None
    _cache = json.loads(DATA_PATH.read_text(encoding="utf-8"))
    return _cache


def state() -> Dict[str, object]:
    stored = measurements()
    live = module_digest()
    if stored is None:
        return {"present": False, "fresh": False, "verdict": "absent",
                "live_digest": live, "stored_digest": None}
    fresh = stored.get("source_digest") == live
    return {"present": True, "fresh": fresh,
            "verdict": "current" if fresh else "stale",
            "live_digest": live, "stored_digest": stored.get("source_digest")}


def current() -> Optional[Dict[str, object]]:
    return measurements() if state()["fresh"] else None


def lorentzian_majority_report() -> Dict[str, object]:
    """The stored marks, or why there are none."""
    stored = current()
    if stored is None:
        return {"available": False, "reason": (
            f"the stored measurement is {state()['verdict']}; re-take it "
            f"with python3 -m glm_universal.tools lorentzian-majority --write")}
    return dict(stored, available=True)
