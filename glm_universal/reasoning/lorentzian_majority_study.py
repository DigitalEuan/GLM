def _examples(rng: random.Random, cond: Tuple[int, int, int], d, c, rels,
              pools) -> Tuple[List[Tuple[str, str]], Optional[tuple]]:
    """The examples of one query, and the colluding relation (if any).

    The single-independent-decoy case makes exactly Phase 183's calls."""
    good, coll, ind = cond
    pool = [p for p in pools[d] if c not in p]
    ex = rng.sample(pool, good)
    if coll == 0 and ind == 1:
        d2 = d
        while d2 == d:
            d2 = rels[rng.randrange(len(rels))]
        bad = [p for p in pools[d2] if c not in p]
        ex.insert(rng.randrange(good + 1), bad[rng.randrange(len(bad))])
        return ex, None
    used = [d]
    dc = None
    if coll:
        while True:
            dc = rels[rng.randrange(len(rels))]
            bad = [p for p in pools[dc] if c not in p]
            if dc not in used and len(bad) >= coll:
                break
        used.append(dc)
        for p in rng.sample(bad, coll):
            ex.insert(rng.randrange(len(ex) + 1), p)
    for _ in range(ind):
        while True:
            di = rels[rng.randrange(len(rels))]
            bad = [p for p in pools[di] if c not in p]
            if di not in used and bad:
                break
        used.append(di)
        ex.insert(rng.randrange(len(ex) + 1), bad[rng.randrange(len(bad))])
    return ex, dc


def physics() -> Dict[str, object]:
    vec, cls = le.physics_classes()
    names = sorted(vec)
    rels = les._relations(vec)
    pools = {d: les._pairs_for(d, vec, names) for d in rels}
    rels = [d for d in rels if len(pools[d]) >= 4]
    out: Dict[str, object] = {"relations": len(rels)}
    for cond, shape in CONDITIONS.items():
        rng = random.Random(f"{SEED}:physics:{cond}")
        rules = {r: _tally() for r in ("guarded", "vote", "majority")}
        present = absent = colluding_present = 0
        for _ in range(QUERIES):
            d = rels[rng.randrange(len(rels))]
            c = names[rng.randrange(len(names))]
            ex, dc = _examples(rng, shape, d, c, rels, pools)
            truth = tuple(x + y for x, y in zip(vec[c], d))
            in_reg = truth in cls
            present += in_reg
            absent += not in_reg
            if dc is not None:
                colluding_present += tuple(
                    x + y for x, y in zip(vec[c], dc)) in cls
            key = truth if in_reg else None
            targets = [x for x, _ in le.target_cues(
                [(vec[a], vec[b]) for a, b in ex], vec[c])]
            ra = le.relation_answer(ex, c, vec, cls)
            _mark(rules["guarded"],
                  ra["target"] if ra["status"] == "class" else None, key)
            counts: Dict[tuple, int] = {}
            for t in targets:
                counts[t] = counts.get(t, 0) + 1
            top = max(counts.values())
            winners = [t for t, v in counts.items() if v == top]
            _mark(rules["vote"],
                  winners[0] if len(winners) == 1 and winners[0] in cls
                  else None, key)
            rm = lm.relation_majority(ex, c, vec, cls)
            _mark(rules["majority"],
                  rm["target"] if rm["status"] == "class" else None, key)
        out[cond] = dict(rules, present=present, absent=absent,
                         colluding_present=colluding_present,
                         shape=list(shape))
    return out


