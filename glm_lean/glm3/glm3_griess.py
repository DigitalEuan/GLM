def norton_sakuma_report(cls: Optional[int] = None) -> Dict[str, object]:
    """
    For each of the three Co_0-orbits of pairs of type-2 classes — |lam.mu|
    equal to 2, 1 or 0 — generate the subalgebra of the two axes and report
    its dimension, the inner product of the axes and the resulting
    Norton-Sakuma type.  For the 2A case the classical relation

        a_lam . a_mu = (1/8) (a_lam + a_mu - a_rho),   rho = lam + mu,

    is checked as an identity (with the sign of the third axis fixed by the
    product, which is the gauge freedom described in the module header).
    """
    tab = type2_table()
    if cls is None:
        cls = next(iter(tab))
    lam = tab[cls]
    a = axis(cls)
    found: Dict[int, int] = {}
    out: Dict[str, object] = {"orbits": {}}
    for c, v in tab.items():
        if c == cls:
            continue
        k = int(abs(std_inner(lam, v)))
        if k in found:
            continue
        found[k] = c
        b = axis(c)
        dim = len(subalgebra_closure([a, b]))
        ip = a.form(b)
        entry = {
            "inner_product": str(ip),
            "dimension": dim,
            "type": NORTON_SAKUMA.get((dim, ip), "unidentified"),
        }
        if k == 2:
            rho = cls ^ c
            lhs = a.mul(b)
            rhs = (a + b - axis(rho, -1)).scale(F(1, 8))
            entry["sakuma_2A_identity"] = lhs == rhs
        if k == 0:
            entry["product_is_zero"] = a.mul(b).is_zero()
        out["orbits"][k] = entry
        if len(found) == 3:
            break
    out["types"] = {k: out["orbits"][k]["type"] for k in sorted(out["orbits"])}
    out["all_identified"] = all(e["type"] != "unidentified"
                                for e in out["orbits"].values())
    return out


