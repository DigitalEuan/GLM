    print(f"  the form is Frobenius        : {a['form_is_frobenius']}")
    print(f"  the algebra is non-associative: {a['non_associative']}")
    if full:
        ns = a["norton_sakuma"]
        print(f"\n[Norton-Sakuma subalgebras, computed as closures]")
        for k in sorted(ns["orbits"]):
            e = ns["orbits"][k]
            extra = ""
