def _zero_matrix() -> Matrix:
    return [[F(0)] * N for _ in range(N)]


def outer(v: Sequence[int]) -> Matrix:
    """P_lam = lam lam^T for the standard normalisation lam = v / sqrt 8."""
    return [[F(int(v[i]) * int(v[j]), 8) for j in range(N)] for i in range(N)]


class GriessVector:
    """
    An element of the even part: a symmetric 24x24 rational matrix (the
    A-part) together with a finitely supported map from type-2 classes to Q
    (the B-part).  Sparse in B, dense in A — which is the right trade-off,
    since A is 300-dimensional and B is 98,280-dimensional.
    """

    __slots__ = ("A", "B")

    def __init__(self, A: Optional[Matrix] = None,
                 B: Optional[Dict[int, F]] = None) -> None:
        self.A: Matrix = A if A is not None else _zero_matrix()
        self.B: Dict[int, F] = {k: F(v) for k, v in (B or {}).items() if v != 0}

    # ── linear structure ────────────────────────────────────────────────
    def __add__(self, other: "GriessVector") -> "GriessVector":
        A = [[self.A[i][j] + other.A[i][j] for j in range(N)] for i in range(N)]
        B = dict(self.B)
        for k, v in other.B.items():
            s = B.get(k, F(0)) + v
            if s:
                B[k] = s
            else:
                B.pop(k, None)
        return GriessVector(A, B)

    def scale(self, c) -> "GriessVector":
        c = F(c)
        A = [[c * self.A[i][j] for j in range(N)] for i in range(N)]
        return GriessVector(A, {k: c * v for k, v in self.B.items()} if c else {})

    def __sub__(self, other: "GriessVector") -> "GriessVector":
        return self + other.scale(-1)

    def is_zero(self) -> bool:
        return (not self.B) and all(x == 0 for row in self.A for x in row)

    def __eq__(self, other: object) -> bool:
        return isinstance(other, GriessVector) and (self - other).is_zero()

    def __repr__(self) -> str:
        tr = sum(self.A[i][i] for i in range(N))
        return (f"GriessVector(A: trace {tr}, "
                f"B: {len(self.B)} classes, norm {self.form(self)})")

    # ── algebra ─────────────────────────────────────────────────────────
    def mul(self, other: "GriessVector") -> "GriessVector":
        """The Griess product, restricted to the even part."""
        tab = type2_table()
        A = _mat_scale(ALPHA, _mat_add(_mat_mul(self.A, other.A),
                                       _mat_mul(other.A, self.A)))
        B: Dict[int, F] = {}

        def bump(c: int, coef: F) -> None:
            if coef:
                s = B.get(c, F(0)) + coef
                if s:
                    B[c] = s
                else:
                    B.pop(c, None)

        for c, coef in other.B.items():
            bump(c, BETA * _quad(self.A, tab[c]) * coef)
        for c, coef in self.B.items():
            bump(c, BETA * _quad(other.A, tab[c]) * coef)
        for c1, k1 in self.B.items():
            for c2, k2 in other.B.items():
                if c1 == c2:
                    A = _mat_add(A, _mat_scale(GAMMA * k1 * k2,
                                               outer(tab[c1])))
                else:
                    c3 = c1 ^ c2
                    if c3 in tab:
                        bump(c3, DELTA * k1 * k2)
        return GriessVector(A, B)

    def form(self, other: "GriessVector") -> F:
        """The invariant bilinear form."""
        s = sum(self.A[i][j] * other.A[i][j] for i in range(N) for j in range(N))
        t = sum(k * other.B.get(c, F(0)) for c, k in self.B.items())
        return FORM_A * s + FORM_B * t

    def support(self) -> int:
        return len(self.B)


def _mat_add(X: Matrix, Y: Matrix) -> Matrix:
    return [[X[i][j] + Y[i][j] for j in range(N)] for i in range(N)]


def _mat_scale(c: F, X: Matrix) -> Matrix:
    return [[c * X[i][j] for j in range(N)] for i in range(N)]


def _mat_mul(X: Matrix, Y: Matrix) -> Matrix:
    out = _zero_matrix()
    for i in range(N):
        Xi = X[i]
        oi = out[i]
        for k in range(N):
            x = Xi[k]
            if x:
                Yk = Y[k]
                for j in range(N):
                    if Yk[j]:
                        oi[j] += x * Yk[j]
    return out


def _quad(X: Matrix, v: Sequence[int]) -> F:
    """lam^T X lam for lam = v / sqrt 8."""
    total = F(0)
    idx = [i for i in range(N) if v[i]]
    for i in idx:
        Xi = X[i]
        vi = int(v[i])
        for j in idx:
            if Xi[j]:
                total += F(vi * int(v[j]), 8) * Xi[j]
    return total


# ── constructors ────────────────────────────────────────────────────────────

def zero() -> GriessVector:
    return GriessVector()


def identity() -> GriessVector:
    """The identity element of the even algebra: the identity matrix in A."""
    A = _zero_matrix()
    for i in range(N):
        A[i][i] = F(1)
    return GriessVector(A)


def b_vector(cls: int, coefficient=1) -> GriessVector:
    return GriessVector(None, {cls: F(coefficient)})


def a_matrix(X: Matrix) -> GriessVector:
    return GriessVector([[F(x) for x in row] for row in X])


def axis(cls: int, sign: int = 1) -> GriessVector:
    """
    The Majorana axis of a type-2 class:

        a_lam^eps  =  (1/8) P_lam  +  eps (1/2) b_lam,     eps = +-1.

    Both signs are idempotents with (a, a) = 1 and the Monster spectrum; the
    two are exchanged by the extraspecial group, and the even part cannot
    tell them apart by their Miyamoto involutions (see the module header).
    """
    if sign not in (1, -1):
        raise ValueError("axis: sign must be +1 or -1")
    v = class_representative(cls)
    return GriessVector(_mat_scale(F(1, 8), outer(v)),
                        {cls: F(sign, 2)})


def axis_of_class(cls: int) -> GriessVector:
    return axis(cls, 1)


