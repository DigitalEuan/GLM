def miyamoto_signs(cls: int) -> Dict[str, object]:
    """
    The Miyamoto involution of the axis a_lam is +1 on V_1 + V_0 + V_{1/4}
    and -1 on V_{1/32}.  Since V_{1/32} is spanned by the b_mu with lam.mu
    odd, and lam.mu mod 2 is exactly the F_2 polar form B(lam, mu) of
    Lambda/2Lambda, the involution IS the extraspecial sign automorphism
    x_lam.  This function checks that identification on a spread of classes.
    """
    tab = type2_table()
    lam = tab[cls]
    agree = True
    checked = 0
    for c, v in tab.items():
        expected = 1 if (int(std_inner(lam, v)) % 2 == 0) else -1
        got = 1 if L2.b_form(cls, c) == 0 else -1
        if expected != got:
            agree = False
        checked += 1
        if checked >= 4000:
            break
    return {"checked": checked, "miyamoto_is_extraspecial_sign": agree}


def apply_sign_automorphism(mu: int, x: GriessVector) -> GriessVector:
    """
    The action of the extraspecial element x_mu (mu a class of
    Lambda/2Lambda) on the even algebra: trivial on A, and b_lam ->
    (-1)^B(lam, mu) b_lam.
    """
    B = {c: (k if L2.b_form(c, mu) == 0 else -k) for c, k in x.B.items()}
    return GriessVector([row[:] for row in x.A], B)


def is_automorphism_on(mu: int, vectors: Sequence[GriessVector]) -> bool:
    """g(x . y) = g(x) . g(y) on the supplied vectors."""
    for i, x in enumerate(vectors):
        for y in vectors[i:]:
            lhs = apply_sign_automorphism(mu, x.mul(y))
            rhs = apply_sign_automorphism(mu, x).mul(
                apply_sign_automorphism(mu, y))
            if lhs != rhs:
                return False
    return True


# ══════════════════════════════════════════════════════════════════════════════
# §6.  SUBALGEBRAS GENERATED BY TWO AXES  (Norton-Sakuma, computed)
# ══════════════════════════════════════════════════════════════════════════════

def _flatten(x: GriessVector, keys: Sequence[int]) -> List[F]:
    out = [x.A[i][j] for i in range(N) for j in range(i, N)]
    out.extend(x.B.get(k, F(0)) for k in keys)
    return out


def _reduce(rows: List[Tuple[int, List[F]]], w: List[F]) -> List[F]:
    for piv, r in rows:
        if w[piv]:
            c = w[piv] / r[piv]
            w = [a - c * b for a, b in zip(w, r)]
    return w


def subalgebra_closure(generators: Sequence[GriessVector],
                       max_dim: int = 24) -> List[GriessVector]:
    """
    A basis of the subalgebra generated by the given elements, computed by
    closing under the product with exact Gaussian elimination.  Raises if the
    dimension exceeds `max_dim` (the dihedral subalgebras of interest here
    are small).
    """
    basis: List[GriessVector] = []
    keys: List[int] = []
    rows: List[Tuple[int, List[F]]] = []

    def rebuild() -> None:
        nonlocal rows
        rows = []
        for e in basis:
            w = _reduce(rows, _flatten(e, keys))
            nz = next((i for i, a in enumerate(w) if a), None)
            if nz is not None:
                rows.append((nz, w))

    def add(x: GriessVector) -> bool:
        nonlocal keys
        new = [c for c in x.B if c not in keys]
        if new:
            keys = keys + sorted(new)
            rebuild()
        w = _reduce(rows, _flatten(x, keys))
        nz = next((i for i, a in enumerate(w) if a), None)
        if nz is None:
            return False
        rows.append((nz, w))
        basis.append(x)
        return True

    for g in generators:
        add(g)
    changed = True
    while changed:
        changed = False
        for i in range(len(basis)):
            for j in range(i, len(basis)):
                if add(basis[i].mul(basis[j])):
                    changed = True
                    if len(basis) > max_dim:
                        raise RuntimeError("subalgebra larger than max_dim")
                    break
            if changed:
                break
    return basis


