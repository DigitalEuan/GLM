EIGENVALUES = (F(1), F(0), F(1, 4), F(1, 32))


def spectrum_dimensions() -> Dict[str, int]:
    """
    The exact dimensions of the four eigenspaces of ad(a_lam) on the whole
    98,580-dimensional even algebra, counted rather than sampled.

      * A splits as  <a-part>  +  {lam w^T + w lam^T : w perp lam}  (23)
        + traceless Sym^2(lam-perp) (275) + the 3-space <P, I, b_lam>;
      * b_mu with lam.mu = 0 (46,575 classes)   -> eigenvalue 0
        b_mu with |lam.mu| = 1 (47,104 classes) -> eigenvalue 1/32
        the 4,600 classes with |lam.mu| = 2 pair up into 2,300 blocks
        {b_mu, b_{lam+mu}}, each contributing one 1/4 and one 0;
      * the 3-space <P_lam, I, b_lam> contributes 1, 0, 0.

    The counts 46,575 / 47,104 / 4,600 are exactly half of the classical
    Leech inner-product census 93,150 / 94,208 / 9,200 computed in
    glm3_leech2.pair_census().
    """
    census = {0: 93150 // 2, 1: 94208 // 2, 2: 9200 // 2}
    d1 = 1
    d0 = census[0] + census[2] // 2 + 275 + 2
    dq = census[2] // 2 + 23
    d32 = census[1]
    return {"1": d1, "0": d0, "1/4": dq, "1/32": d32,
            "total": d1 + d0 + dq + d32, "expected": DIM_EVEN}


def eigen_filter(a: GriessVector, x: GriessVector,
                 values: Sequence[F]) -> GriessVector:
    """Apply prod_{lam in values} (ad_a - lam) to x."""
    y = x
    for lam in values:
        y = a.mul(y) - y.scale(lam)
    return y


def in_eigenspace(a: GriessVector, x: GriessVector,
                  values: Sequence[F]) -> bool:
    """Does x lie in the sum of the listed eigenspaces of ad_a?"""
    return eigen_filter(a, x, values).is_zero()


def _eigen_samples(cls: int, count: int = 3) -> Dict[str, List[GriessVector]]:
    """
    A spread of eigenvectors of ad(a_lam), one family per eigenvalue, built
    from the class census rather than from a numerical eigensolver.
    """
    tab = type2_table()
    lam = tab[cls]
    out: Dict[str, List[GriessVector]] = {"0": [], "1/4": [], "1/32": []}
    perp: List[Tuple[int, ...]] = []
    seen_pairs = set()
    for c, v in tab.items():
        if c == cls:
            continue
        k = abs(std_inner(lam, v))
        if k == 0:
            if len(out["0"]) < count:
                out["0"].append(b_vector(c))
            if len(perp) < count:
                perp.append(v)
        elif k == 1 and len(out["1/32"]) < count:
            out["1/32"].append(b_vector(c))
        elif k == 2 and c not in seen_pairs and len(out["1/4"]) < count:
            partner = c ^ cls
            seen_pairs.add(c)
            seen_pairs.add(partner)
            out["1/4"].append(b_vector(c) + b_vector(partner))
            out["0"].append(b_vector(c) - b_vector(partner))
        if (len(out["0"]) >= 2 * count and len(out["1/4"]) >= count
                and len(out["1/32"]) >= count and len(perp) >= count):
            break
    # A-part eigenvectors: lam w^T + w lam^T with w perp lam has eigenvalue 1/4
    for w in perp:
        M = [[F(int(lam[i]) * int(w[j]) + int(w[i]) * int(lam[j]), 8)
              for j in range(N)] for i in range(N)]
        out["1/4"].append(GriessVector(M))
    return out


