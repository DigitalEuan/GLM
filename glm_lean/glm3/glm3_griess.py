N = 24

ALPHA = F(1, 2)     # A . A   = alpha (A1 A2 + A2 A1)
BETA = F(1, 4)      # A . b   = beta (lam^T A lam) b
GAMMA = F(1, 4)     # b . b   = gamma P_lam
DELTA = F(1, 4)     # b_lam . b_mu = delta b_{lam+mu}
FORM_A = F(2)       # (A1, A2) = FORM_A tr(A1 A2)
FORM_B = F(2)       # (b, b)   = FORM_B

