def type2_table() -> Dict[int, Tuple[int, ...]]:
    """
    class -> a chosen minimal vector in it.  Built once by streaming the
    196,560 minimal vectors of Lambda; the choice of +-v does not matter,
    because every formula below uses either P_lam (even in the sign) or the
    class sum, which is sign-blind.
    """
    global _TABLE
    if _TABLE is None:
        _TABLE = L2.type2_class_table()
    return _TABLE


def class_representative(cls: int) -> Tuple[int, ...]:
    return type2_table()[cls]


def std_inner(v: Sequence[int], w: Sequence[int]) -> F:
    """
    The inner product in the STANDARD normalisation, in which minimal
    vectors have norm 4.  GLM-2 stores Lambda in the "times sqrt 8" integer
    model, so this is the integer inner product divided by 8.
    """
    return F(LAT.inner(v, w), 8)


