# §4.  FUSION
# ══════════════════════════════════════════════════════════════════════════════

#: The Monster (Ising) fusion law.  Star-products of eigenspaces land in the
#: sum of the eigenspaces listed.
FUSION_LAW: Dict[Tuple[str, str], Tuple[str, ...]] = {
    ("0", "0"): ("0",),
    ("0", "1/4"): ("1/4",),
    ("0", "1/32"): ("1/32",),
    ("1/4", "1/4"): ("1", "0"),
    ("1/4", "1/32"): ("1/32",),
    ("1/32", "1/32"): ("1", "0", "1/4"),
}

_VALUE = {"1": F(1), "0": F(0), "1/4": F(1, 4), "1/32": F(1, 32)}


def fusion_report(cls: int, count: int = 3) -> Dict[str, object]:
    """
    Verify every rule of the Monster fusion law for the axis of `cls`, on a
    spread of genuine eigenvectors.  Returns one boolean per rule.
    """
    a = axis(cls)
    samples = _eigen_samples(cls, count)
    out: Dict[str, object] = {}
    # first: the samples really are eigenvectors
    eigen_ok = True
    for name, vs in samples.items():
        for v in vs:
            if not in_eigenspace(a, v, [_VALUE[name]]):
                eigen_ok = False
    out["samples_are_eigenvectors"] = eigen_ok
    out["idempotent"] = a.mul(a) == a
    out["norm_one"] = a.form(a) == 1
    rules: Dict[str, bool] = {}
    for (p, q), targets in FUSION_LAW.items():
        vals = [_VALUE[t] for t in targets]
        ok = True
        for x in samples[p]:
            for y in samples[q]:
                if not in_eigenspace(a, x.mul(y), vals):
                    ok = False
        rules[f"{p} * {q} -> {'+'.join(targets)}"] = ok
    out["rules"] = rules
    out["all_rules_hold"] = all(rules.values())
    return out


