def griess_audit(full: bool = True) -> Dict[str, object]:
    tab = type2_table()
    cls = next(iter(tab))
    a = axis(cls)
    e = identity()
    out: Dict[str, object] = {}
    out["classes"] = len(tab)
    out["dimension"] = {"A": DIM_A, "B": len(tab), "even": DIM_A + len(tab),
                        "matches": DIM_A + len(tab) == DIM_EVEN}
    out["identity_acts"] = (e.mul(a) == a and e.mul(e) == e
                            and e.mul(b_vector(cls)) == b_vector(cls))
    out["axis_idempotent"] = a.mul(a) == a
    out["axis_norm"] = str(a.form(a))
    out["axis_minus_idempotent"] = axis(cls, -1).mul(axis(cls, -1)) == axis(cls, -1)
    out["spectrum_dimensions"] = spectrum_dimensions()
    out["fusion"] = fusion_report(cls, count=2 if not full else 3)
    out["miyamoto"] = miyamoto_signs(cls)
    samples = [a, b_vector(cls), identity()]
    extra = [b_vector(c) for c in list(tab)[1:4]]
    out["extraspecial_is_automorphism"] = is_automorphism_on(
        next(iter(tab)) ^ 0b1011, samples + extra)
    # the form is Frobenius on a spread of vectors
    frob = True
    vs = samples + extra
    for i, x in enumerate(vs):
        for y in vs:
            for w in vs:
                if x.mul(y).form(w) != x.form(y.mul(w)):
                    frob = False
    out["form_is_frobenius"] = frob
    # non-associativity: exhibited on two axes that generate a 2A algebra
    partner = None
    lam = tab[cls]
    for c, v in tab.items():
        if c != cls and abs(std_inner(lam, v)) == 2:
            partner = c
            break
    b = axis(partner)
    witness = a.mul(a.mul(b)) - (a.mul(a)).mul(b)
    out["non_associative"] = not witness.is_zero()
    out["associator_norm"] = str(witness.form(witness))
    if full:
        out["norton_sakuma"] = norton_sakuma_report(cls)
    return out


def main(argv: Optional[Sequence[str]] = None) -> None:
    argv = list(argv if argv is not None else sys.argv[1:])
    full = "--quick" not in argv
    print(banner("GLM-3  GRIESS  —  the even part of the Monster algebra"))
    a = griess_audit(full=full)
    d = a["dimension"]
    print(f"\n[dimension]")
    print(f"  A = Sym^2(R^24)              : {fmt_int(d['A'])}")
    print(f"  B = type-2 classes           : {fmt_int(d['B'])}")
    print(f"  even part                    : {fmt_int(d['even'])}"
          f"  (300 + 98,280 : {d['matches']})")
    print(f"\n[axis]")
    print(f"  identity element acts        : {a['identity_acts']}")
    print(f"  a is idempotent              : {a['axis_idempotent']}")
    print(f"  (a, a)                       : {a['axis_norm']}")
    print(f"  the other sign is an axis too: {a['axis_minus_idempotent']}")
    s = a["spectrum_dimensions"]
    print(f"  eigenspace dimensions        : 1 -> {fmt_int(s['1'])}, "
          f"0 -> {fmt_int(s['0'])}, 1/4 -> {fmt_int(s['1/4'])}, "
          f"1/32 -> {fmt_int(s['1/32'])}")
    print(f"  they sum to                  : {fmt_int(s['total'])} "
          f"(expected {fmt_int(s['expected'])})")
    f = a["fusion"]
    print(f"\n[the Monster fusion law]")
    print(f"  samples are eigenvectors     : {f['samples_are_eigenvectors']}")
    for name, ok in f["rules"].items():
        print(f"    {name:28s} {ok}")
    print(f"  all rules hold               : {f['all_rules_hold']}")
    print(f"\n[the group]")
    print(f"  Miyamoto = extraspecial sign : "
          f"{a['miyamoto']['miyamoto_is_extraspecial_sign']}")
